//! Deterministic Rust code generator for Jarvis daemon components.
//!
//! Generation Gap pattern: gen_{name}.rs (scaffold) + {name}_impl.rs (LLM stubs).

use crate::ir::{ComponentDecl, JarvisEvent, StateDep};

/// Generate scaffold + trait stubs for a component.
/// Returns `(gen_file_content, impl_file_content)`.
pub fn generate_component(decl: &ComponentDecl) -> (String, String) {
    (generate_scaffold(decl), generate_impl_stubs(decl))
}

fn generate_scaffold(decl: &ComponentDecl) -> String {
    let struct_name = to_pascal_case(&decl.name);
    let mut out = String::with_capacity(2048);

    out.push_str(&format!(
        "// AUTO-GENERATED by jarvis-forge — DO NOT EDIT\n//! Scaffold for `{}`\n//! Role: {}\n\n",
        decl.name, decl.role
    ));
    out.push_str("use std::sync::Arc;\nuse anyhow::Result;\nuse tokio::sync::broadcast;\nuse tracing::{info, warn};\n");

    if !decl.listens_to.is_empty() {
        out.push_str("use crate::types::Event;\n");
    }
    for dep in &decl.state_deps {
        match dep {
            StateDep::Storage => out.push_str("use crate::memory::storage::Storage;\n"),
            StateDep::SessionManager => out.push_str("use crate::control::session::SessionManager;\n"),
            StateDep::TopologyManager => out.push_str("use crate::memory::topology_manager::TopologyManager;\n"),
            StateDep::RealityMirror => out.push_str("use crate::memory::reality_mirror::RealityMirror;\n"),
            StateDep::EventBus => {}
        }
    }

    // Struct
    out.push_str(&format!("\npub struct {struct_name} {{\n"));
    for dep in &decl.state_deps {
        let (f, t) = dep_field(dep);
        out.push_str(&format!("    pub {f}: {t},\n"));
    }
    if !decl.listens_to.is_empty() {
        out.push_str("    event_rx: broadcast::Receiver<Event>,\n");
    }
    out.push_str("}\n\n");

    // Constructor
    out.push_str(&format!("impl {struct_name} {{\n    pub fn new(\n"));
    for dep in &decl.state_deps {
        let (f, t) = dep_field(dep);
        out.push_str(&format!("        {f}: {t},\n"));
    }
    if !decl.listens_to.is_empty() {
        out.push_str("        event_rx: broadcast::Receiver<Event>,\n");
    }
    out.push_str("    ) -> Self {\n        Self {");
    for dep in &decl.state_deps {
        let (f, _) = dep_field(dep);
        out.push_str(&format!(" {f},"));
    }
    if !decl.listens_to.is_empty() { out.push_str(" event_rx,"); }
    out.push_str(" }\n    }\n\n");

    // Event loop
    if !decl.listens_to.is_empty() {
        out.push_str("    pub async fn run(mut self) -> Result<()> {\n");
        out.push_str(&format!("        info!(\"{struct_name} started\");\n        loop {{\n            match self.event_rx.recv().await {{\n"));
        for event in &decl.listens_to {
            let (pat, args) = event_pattern(event);
            let handler = event_handler(event);
            out.push_str(&format!(
                "                Ok({pat}) => {{ let _ = self.{handler}({args}).await; }}\n"
            ));
        }
        out.push_str("                Err(broadcast::error::RecvError::Lagged(n)) => { warn!(missed = n, \"lagged\"); }\n");
        out.push_str("                _ => {}\n            }\n        }\n    }\n");
    }
    out.push_str("}\n");
    out
}

fn generate_impl_stubs(decl: &ComponentDecl) -> String {
    let struct_name = to_pascal_case(&decl.name);
    let mod_name = decl.name.replace('-', "_");
    let mut out = String::with_capacity(1024);

    out.push_str(&format!(
        "//! Logic implementation for {struct_name} — LLM fills in function bodies.\n\n\
         use anyhow::Result;\nuse super::gen_{mod_name}::{struct_name};\n\n\
         impl {struct_name} {{\n"
    ));

    for event in &decl.listens_to {
        let handler = event_handler(event);
        let (_, sig) = event_sig(event);
        out.push_str(&format!(
            "    pub async fn {handler}(&mut self{sig}) -> Result<()> {{\n\
             \x20       // TODO(llm): implement\n        Ok(())\n    }}\n\n"
        ));
    }

    for func in &decl.logic_fns {
        let params: String = func.inputs.iter().map(|(n, t)| format!(", {n}: {t}")).collect();
        out.push_str(&format!("    pub async fn {}(&self{params}) -> {} {{\n", func.name, func.output));
        for step in &func.steps { out.push_str(&format!("        // {step}\n")); }
        out.push_str("        todo!()\n    }\n\n");
    }

    out.push_str("}\n");
    out
}

fn dep_field(dep: &StateDep) -> (&'static str, &'static str) {
    match dep {
        StateDep::Storage => ("storage", "Arc<Storage>"),
        StateDep::SessionManager => ("session_mgr", "Arc<SessionManager>"),
        StateDep::EventBus => ("event_tx", "broadcast::Sender<Event>"),
        StateDep::TopologyManager => ("topology_mgr", "Arc<TopologyManager>"),
        StateDep::RealityMirror => ("reality_mirror", "Arc<RealityMirror>"),
    }
}

fn event_pattern(e: &JarvisEvent) -> (String, String) {
    match e {
        JarvisEvent::CodebaseMutated => ("Event::CodebaseMutated { ref reason, .. }".into(), "reason".into()),
        JarvisEvent::MessagesIngested => ("Event::MessagesIngested { session_id, count }".into(), "session_id, count".into()),
        JarvisEvent::UserMessageReceived => ("Event::UserMessageReceived { session_id, ref content }".into(), "session_id, content".into()),
        JarvisEvent::Custom(n) => (format!("Event::Custom {{ ref name, ref payload }} if name == \"{n}\""), "payload".into()),
        _ => (format!("Event::{e:?} {{ .. }}"), "".into()),
    }
}

fn event_handler(e: &JarvisEvent) -> String {
    match e {
        JarvisEvent::MessagesIngested => "on_messages_ingested".into(),
        JarvisEvent::SessionStateChanged => "on_session_state_changed".into(),
        JarvisEvent::UserMessageReceived => "on_user_message_received".into(),
        JarvisEvent::TextComplete => "on_text_complete".into(),
        JarvisEvent::ContextReady => "on_context_ready".into(),
        JarvisEvent::ToolCalled => "on_tool_called".into(),
        JarvisEvent::CodebaseMutated => "on_codebase_mutated".into(),
        JarvisEvent::Custom(n) => format!("on_{}", n.replace('-', "_")),
    }
}

fn event_sig(e: &JarvisEvent) -> (String, String) {
    match e {
        JarvisEvent::CodebaseMutated => ("on_codebase_mutated".into(), ", reason: &str".into()),
        JarvisEvent::MessagesIngested => ("on_messages_ingested".into(), ", session_id: uuid::Uuid, count: usize".into()),
        JarvisEvent::UserMessageReceived => ("on_user_message_received".into(), ", session_id: uuid::Uuid, content: &str".into()),
        _ => (event_handler(e), "".into()),
    }
}

fn to_pascal_case(s: &str) -> String {
    s.split('-').map(|p| {
        let mut c = p.chars();
        match c.next() {
            None => String::new(),
            Some(f) => f.to_uppercase().to_string() + c.as_str(),
        }
    }).collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::PillarKind;

    #[test]
    fn test_scaffold_shape() {
        let decl = ComponentDecl {
            pillar: PillarKind::Memory,
            name: "message-persister".into(),
            role: "Persists messages".into(),
            depends_on: vec!["storage".into()],
            listens_to: vec![JarvisEvent::MessagesIngested],
            state_deps: vec![StateDep::Storage],
            invariants: vec![], data_flow: None, logic_fns: vec![],
        };
        let (gen, imp) = generate_component(&decl);
        assert!(gen.contains("pub struct MessagePersister"));
        assert!(gen.contains("pub async fn run("));
        assert!(gen.contains("DO NOT EDIT"));
        assert!(imp.contains("TODO(llm)"));
    }
}
