#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_v3_file() {
        let nodes = vec![ComfyNodeDecl {
            class_name: "Canny".into(),
            category: "image/preprocessors".into(),
            description: None,
            display_name: Some("Canny".into()),
            function: "execute".into(),
            output_node: false,
            deprecated: false, v3: false,
            search_aliases: vec![],
            required: vec![ComfyInputDecl {
                name: "image".into(),
                io_type: ComfyIOType::Image,
                options: ComfyInputOptions::default(),
            }],
            optional: vec![],
            hidden: vec![],
            return_types: vec![ComfyIOType::Image],
            return_names: vec![],
            output_tooltips: vec![],
        }];

        let code = generate_comfy_schema_node(&nodes);
        assert!(code.contains("GENERATED BY FORGE"));
        assert!(code.contains("from comfy_api.latest import io"));
        assert!(code.contains("class Canny_ForgeBase(io.ComfyNode):"));
        assert!(code.contains("io.Schema("));
    }
}
