//! ComfyUI V3 Schema Node generator (Layer 2 Pattern).
//!
//! Generates `_ForgeBase` classes using the V3 `io.Schema(...)` API.
//! This is the modern ComfyUI node API, cleaner than legacy INPUT_TYPES.

use nc_jarvis_ir::python::comfy_node::*;

use crate::common::{forge_header, w};
use crate::python::atoms::py_schema_node::gen_schema_node;

/// Generate all V3 `_ForgeBase` classes for a set of ComfyUI nodes.
pub fn generate_comfy_schema_node(nodes: &[ComfyNodeDecl]) -> String {
    let mut out = String::with_capacity(nodes.len() * 1024);

    forge_header(&mut out, "python", ".missiond/intent-comfy.lisp");
    out.push('\n');

    // Imports
    w(&mut out, 0, "from comfy_api.latest import io");
    out.push('\n');

    for (i, decl) in nodes.iter().enumerate() {
        if i > 0 {
            out.push('\n');
        }
        let class_code = gen_schema_node(decl);
        out.push_str(&class_code);
    }

    out
}

