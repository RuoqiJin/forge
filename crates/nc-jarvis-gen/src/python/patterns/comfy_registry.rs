#[cfg(test)]
mod tests {
    use super::*;
    use nc_jarvis_ir::python::comfy_node::*;

    #[test]
    fn generates_registry() {
        let nodes = vec![
            ComfyNodeDecl {
                class_name: "CLIPTextEncode".into(),
                category: "conditioning".into(),
                description: None,
                display_name: Some("CLIP Text Encode (Prompt)".into()),
                function: "encode".into(),
                output_node: false,
                deprecated: false, v3: false,
                search_aliases: vec![],
                required: vec![],
                optional: vec![],
                hidden: vec![],
                return_types: vec![],
                return_names: vec![],
                output_tooltips: vec![],
            },
            ComfyNodeDecl {
                class_name: "SaveImage".into(),
                category: "image".into(),
                description: None,
                display_name: Some("Save Image".into()),
                function: "save_images".into(),
                output_node: true,
                deprecated: false, v3: false,
                search_aliases: vec![],
                required: vec![],
                optional: vec![],
                hidden: vec![],
                return_types: vec![],
                return_names: vec![],
                output_tooltips: vec![],
            },
        ];

        let code = generate_comfy_registry(&nodes, "nodes");

        assert!(code.contains("GENERATED BY FORGE"));
        assert!(code.contains("from nodes import CLIPTextEncode, SaveImage"));
        assert!(code.contains("NODE_CLASS_MAPPINGS = {"));
        assert!(code.contains("    \"CLIPTextEncode\": CLIPTextEncode,"));
        assert!(code.contains("    \"SaveImage\": SaveImage,"));
        assert!(code.contains("NODE_DISPLAY_NAME_MAPPINGS = {"));
        assert!(code.contains("    \"CLIPTextEncode\": \"CLIP Text Encode (Prompt)\","));
        assert!(code.contains("    \"SaveImage\": \"Save Image\","));
    }

    #[test]
    fn fallback_display_name() {
        let nodes = vec![ComfyNodeDecl {
            class_name: "MyNode".into(),
            category: "test".into(),
            description: None,
            display_name: None,
            function: "run".into(),
            output_node: false,
            deprecated: false, v3: false,
            search_aliases: vec![],
            required: vec![],
            optional: vec![],
            hidden: vec![],
            return_types: vec![],
            return_names: vec![],
            output_tooltips: vec![],
        }];

        let code = generate_comfy_registry(&nodes, "nodes");
        assert!(code.contains("\"MyNode\": \"MyNode\","));
    }
}
