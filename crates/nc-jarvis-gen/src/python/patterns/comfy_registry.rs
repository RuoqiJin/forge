//! ComfyUI Node Registry generator (Layer 2 Pattern).
//!
//! Generates `NODE_CLASS_MAPPINGS` and `NODE_DISPLAY_NAME_MAPPINGS` dicts
//! from a set of ComfyNodeDecl. Imports from the human-written subclass module,
//! NOT from the _ForgeBase.

use nc_jarvis_ir::python::comfy_node::ComfyNodeDecl;

use crate::common::{forge_header, w};

/// Generate the registry file with NODE_CLASS_MAPPINGS and NODE_DISPLAY_NAME_MAPPINGS.
///
/// `import_module` is the Python module to import classes from (e.g., "nodes").
pub fn generate_comfy_registry(nodes: &[ComfyNodeDecl], import_module: &str) -> String {
    let mut out = String::with_capacity(nodes.len() * 128);

    forge_header(&mut out, "python", ".missiond/intent-comfy.lisp");
    out.push('\n');

    // Import all node classes from the human-written module
    let class_names: Vec<&str> = nodes.iter().map(|n| n.class_name.as_str()).collect();
    w(
        &mut out,
        0,
        &format!("from {import_module} import {}", class_names.join(", ")),
    );
    out.push('\n');
    out.push('\n');

    // NODE_CLASS_MAPPINGS
    w(&mut out, 0, "NODE_CLASS_MAPPINGS = {");
    for decl in nodes {
        w(
            &mut out,
            1,
            &format!("\"{}\": {},", decl.class_name, decl.class_name),
        );
    }
    w(&mut out, 0, "}");
    out.push('\n');

    // NODE_DISPLAY_NAME_MAPPINGS
    w(&mut out, 0, "NODE_DISPLAY_NAME_MAPPINGS = {");
    for decl in nodes {
        let display = decl
            .display_name
            .as_deref()
            .unwrap_or(&decl.class_name);
        w(
            &mut out,
            1,
            &format!("\"{}\": \"{}\",", decl.class_name, display),
        );
    }
    w(&mut out, 0, "}");
    out.push('\n');

    out
}

