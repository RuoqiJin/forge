//! Shared codegen utilities — language-agnostic helpers.
//!
//! Used by both rust/ and ts/ generation pipelines.

/// Append a line to the output buffer with `indent` levels of indentation.
///
/// Uses 4 spaces per level (standard for both Rust and TypeScript).
#[inline]
pub fn w(out: &mut String, indent: usize, line: &str) {
    for _ in 0..indent {
        out.push_str("    ");
    }
    out.push_str(line);
    out.push('\n');
}

/// Append a blank line.
#[inline]
pub fn blank(out: &mut String) {
    out.push('\n');
}

/// Standard forge header comment.
pub fn forge_header(out: &mut String, lang: &str, source: &str) {
    let comment = match lang {
        "python" => "#",
        _ => "//",
    };
    w(out, 0, &format!("{comment} 🤖 GENERATED BY FORGE - DO NOT EDIT"));
    w(out, 0, &format!("{comment} Source: {source}"));
}
