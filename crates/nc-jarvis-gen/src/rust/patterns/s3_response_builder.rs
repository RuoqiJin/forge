    /// Full integration test: read real Lisp -> IR -> codegen -> write to .forge-output/
    #[test]
    #[ignore] // requires local xiaojinpro-gateway checkout
    fn full_stamp_from_real_lisp() {
        let lisp_path = "fixtures/xjpfs/.missiond/intent-s3-response-builders.lisp";
        let lisp_src = match std::fs::read_to_string(lisp_path) {
            Ok(s) => s,
            Err(_) => return, // skip if file not available
        };
        let node = nc_parser::SexpNode::parse_one(&lisp_src).expect("Failed to parse S-EXP");
        let decl = S3ResponseBuilderDecl::from_sexp(&node).expect("Failed to lower to IR");

        // Verify IR counts
        assert_eq!(decl.builders.len(), 34, "expected 34 total builders");
        assert_eq!(
            decl.count_by_kind(&BuilderKind::Default),
            4,
            "expected 4 default builders"
        );
        assert_eq!(
            decl.count_by_kind(&BuilderKind::Const),
            4,
            "expected 4 const builders"
        );
        assert_eq!(
            decl.count_by_kind(&BuilderKind::Wrap),
            9,
            "expected 9 wrap builders"
        );
        assert_eq!(
            decl.count_by_kind(&BuilderKind::Custom),
            17,
            "expected 17 custom builders"
        );

        // Generate
        let generated = generate_s3_response_builders(&decl);
        let custom = generate_s3_response_custom(&decl);

        // Balanced braces
        let g_open = generated.chars().filter(|c| *c == '{').count();
        let g_close = generated.chars().filter(|c| *c == '}').count();
        assert_eq!(g_open, g_close, "generated_builders.rs unbalanced braces");

        let c_open = custom.chars().filter(|c| *c == '{').count();
        let c_close = custom.chars().filter(|c| *c == '}').count();
        assert_eq!(c_open, c_close, "custom_builders.rs unbalanced braces");

        // Key assertions on generated code
        assert!(generated.contains("// --- Default builders ---"));
        assert!(generated.contains("// --- Const builders ---"));
        assert!(generated.contains("// --- Wrap builders ---"));
        assert!(generated.contains("// --- Custom trampolines ---"));

        // Default builders
        assert!(generated.contains("PutBucketEncryptionOutput::default()"));
        assert!(generated.contains("PutBucketTaggingOutput::default()"));
        assert!(generated.contains("PutBucketReplicationOutput::default()"));
        assert!(generated.contains("DeleteBucketTaggingOutput::default()"));

        // Const builders
        assert!(generated.contains("full_control_grants()"));
        assert!(generated.contains("rustfs_owner()"));
        assert!(generated.contains("RequestCharged::REQUESTER"));

        // Wrap builders
        assert!(generated.contains("server_side_encryption_configuration:"));
        assert!(generated.contains("object_lock_configuration:"));
        assert!(generated.contains("replication_configuration: Some(replication_configuration),"));

        // Custom trampolines
        assert!(generated.contains("custom_build_list_objects_v2_output("));
        assert!(generated.contains("custom_parse_list_object_versions_params("));
        assert!(generated.contains("custom_s3_response(output)"));
        assert!(generated.contains("custom_validate_object_tag_set(tag_set)"));

        // Custom scaffold
        assert!(custom.contains("pub(crate) fn custom_build_list_objects_v2_output("));
        assert!(custom.contains("pub(crate) fn custom_parse_list_object_versions_params("));
        assert!(custom.contains("pub(crate) fn custom_s3_response<T>(output: T) -> S3Response<T>"));
        assert!(custom.contains("todo!(\"migrate from original s3_api module\")"));

        // Write to .forge-output/s3_api/
        let output_dir =
            "fixtures/xjpfs/.forge-output/s3_api";
        std::fs::create_dir_all(output_dir).expect("create .forge-output/s3_api");
        std::fs::write(
            format!("{}/generated_builders.rs", output_dir),
            &generated,
        )
        .expect("write generated_builders.rs");
        std::fs::write(
            format!("{}/custom_builders.rs", output_dir),
            &custom,
        )
        .expect("write custom_builders.rs");

        eprintln!("=== S3 RESPONSE BUILDER STAMP COMPLETE ===");
        eprintln!(
            "generated_builders.rs: {} lines",
            generated.lines().count()
        );
        eprintln!("custom_builders.rs: {} lines", custom.lines().count());
        eprintln!("Output: {}", output_dir);
    }
