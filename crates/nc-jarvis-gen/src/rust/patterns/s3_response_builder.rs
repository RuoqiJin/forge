    #[test]
    fn generated_has_balanced_braces() {
        let decl = make_minimal_decl();
        let code = generate_s3_response_builders(&decl);
        let opens = code.chars().filter(|c| *c == '{').count();
        let closes = code.chars().filter(|c| *c == '}').count();
        assert_eq!(opens, closes, "unbalanced braces:\n{}", code);
    }

