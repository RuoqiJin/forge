//! S3 Response Builder code generator.
//!
//! Generates the "S3 response builder layer":
//! - `generated_builders.rs` — Default/Const/Wrap builders (fully generated)
//! - `custom_builders.rs` — Custom trampolines calling into hand-written logic
//!
//! Two entry points:
//! - `generate_s3_response_builders` -> **generated_builders.rs** (regenerated on every forge run)
//! - `generate_s3_response_custom` -> **custom_builders.rs** (write-once scaffold)

use nc_jarvis_ir::s3_response_builder::*;

use crate::rust::atoms::w;

// ---------------------------------------------------------------------------
// Public entry points
// ---------------------------------------------------------------------------

/// Generate **generated_builders.rs** — Default, Const, and Wrap builders.
pub fn generate_s3_response_builders(decl: &S3ResponseBuilderDecl) -> String {
    let mut out = String::with_capacity(8192);

    gen_header(&mut out, decl);
    gen_imports(&mut out, decl);
    out.push('\n');

    // --- Default builders ---
    let defaults: Vec<&BuilderDecl> = decl
        .builders
        .iter()
        .filter(|b| b.kind == BuilderKind::Default)
        .collect();
    if !defaults.is_empty() {
        w(&mut out, 0, "// --- Default builders ---");
        w(&mut out, 0, "");
        for b in &defaults {
            gen_default_builder(&mut out, b);
        }
    }

    // --- Const builders ---
    let consts: Vec<&BuilderDecl> = decl
        .builders
        .iter()
        .filter(|b| b.kind == BuilderKind::Const)
        .collect();
    if !consts.is_empty() {
        w(&mut out, 0, "// --- Const builders ---");
        w(&mut out, 0, "");
        for b in &consts {
            gen_const_builder(&mut out, b);
        }
    }

    // --- Wrap builders ---
    let wraps: Vec<&BuilderDecl> = decl
        .builders
        .iter()
        .filter(|b| b.kind == BuilderKind::Wrap)
        .collect();
    if !wraps.is_empty() {
        w(&mut out, 0, "// --- Wrap builders ---");
        w(&mut out, 0, "");
        for b in &wraps {
            gen_wrap_builder(&mut out, b);
        }
    }

    // --- Custom trampolines ---
    let customs: Vec<&BuilderDecl> = decl
        .builders
        .iter()
        .filter(|b| b.kind == BuilderKind::Custom)
        .collect();
    if !customs.is_empty() {
        w(&mut out, 0, "// --- Custom trampolines ---");
        w(&mut out, 0, "");
        for b in &customs {
            gen_custom_trampoline(&mut out, b);
        }
    }

    out
}

/// Generate **custom_builders.rs** — write-once scaffold for custom builders.
pub fn generate_s3_response_custom(decl: &S3ResponseBuilderDecl) -> String {
    let mut out = String::with_capacity(4096);

    gen_custom_header(&mut out);
    w(&mut out, 0, "");

    let customs: Vec<&BuilderDecl> = decl
        .builders
        .iter()
        .filter(|b| b.kind == BuilderKind::Custom)
        .collect();

    for (i, b) in customs.iter().enumerate() {
        gen_custom_impl(&mut out, b);
        if i < customs.len() - 1 {
            w(&mut out, 0, "");
        }
    }

    out
}

// ---------------------------------------------------------------------------
// Header + imports (generated_builders.rs)
// ---------------------------------------------------------------------------

fn gen_header(out: &mut String, decl: &S3ResponseBuilderDecl) {
    w(out, 0, "// \u{1f916} GENERATED BY FORGE - DO NOT EDIT");
    w(
        out,
        0,
        &format!(
            "// Source: .missiond/intent-s3-response-builders.lisp (s3-response-builder {})",
            decl.name
        ),
    );
    w(
        out,
        0,
        "// Pattern: s3-response-builder (S3 DTO response construction layer)",
    );
    w(
        out,
        0,
        &format!(
            "// Default: {} | Const: {} | Wrap: {} | Custom: {}",
            decl.count_by_kind(&BuilderKind::Default),
            decl.count_by_kind(&BuilderKind::Const),
            decl.count_by_kind(&BuilderKind::Wrap),
            decl.count_by_kind(&BuilderKind::Custom),
        ),
    );
    w(out, 0, "");
}

fn gen_imports(out: &mut String, decl: &S3ResponseBuilderDecl) {
    for imp in &decl.imports {
        w(out, 0, &format!("use {};", imp));
    }

    // Import custom module if there are custom builders
    if decl.count_by_kind(&BuilderKind::Custom) > 0 {
        w(out, 0, "use super::custom_builders::*;");
    }
}

// ---------------------------------------------------------------------------
// Default builders: Output::default()
// ---------------------------------------------------------------------------

fn gen_default_builder(out: &mut String, b: &BuilderDecl) {
    w(
        out,
        0,
        &format!(
            "pub(crate) fn {}() -> {} {{",
            b.name, b.output_type
        ),
    );
    w(
        out,
        1,
        &format!("{}::default()", b.output_type),
    );
    w(out, 0, "}");
    w(out, 0, "");
}

// ---------------------------------------------------------------------------
// Const builders: hardcoded expression
// ---------------------------------------------------------------------------

fn gen_const_builder(out: &mut String, b: &BuilderDecl) {
    w(
        out,
        0,
        &format!(
            "pub(crate) fn {}() -> {} {{",
            b.name, b.output_type
        ),
    );
    if let Some(ref body) = b.body {
        w(out, 1, body);
    }
    w(out, 0, "}");
    w(out, 0, "");
}

// ---------------------------------------------------------------------------
// Wrap builders: params -> output fields
// ---------------------------------------------------------------------------

fn gen_wrap_builder(out: &mut String, b: &BuilderDecl) {
    // Function signature
    let param_list = gen_param_list(&b.params);
    w(
        out,
        0,
        &format!(
            "pub(crate) fn {}({}) -> {} {{",
            b.name, param_list, b.output_type
        ),
    );

    // Struct construction
    w(out, 1, &format!("{} {{", b.output_type));
    for (field_name, field_expr) in &b.fields {
        w(out, 2, &format!("{}: {},", field_name, field_expr));
    }
    // Only add ..Default::default() if the struct might have more fields
    w(out, 2, "..Default::default()");
    w(out, 1, "}");

    w(out, 0, "}");
    w(out, 0, "");
}

// ---------------------------------------------------------------------------
// Custom trampolines
// ---------------------------------------------------------------------------

fn gen_custom_trampoline(out: &mut String, b: &BuilderDecl) {
    let param_list = gen_param_list(&b.params);
    let generic_prefix = match &b.generic {
        Some(g) => format!("<{}>", g),
        None => String::new(),
    };
    w(
        out,
        0,
        &format!(
            "pub(crate) fn {}{}({}) -> {} {{",
            b.name, generic_prefix, param_list, b.output_type
        ),
    );

    // Forward to custom implementation
    let arg_list = gen_arg_list(&b.params);
    w(
        out,
        1,
        &format!("custom_{}({})", b.name, arg_list),
    );

    w(out, 0, "}");
    w(out, 0, "");
}

// ---------------------------------------------------------------------------
// custom_builders.rs generation
// ---------------------------------------------------------------------------

fn gen_custom_header(out: &mut String) {
    w(
        out,
        0,
        "// XjpFS custom S3 response builders \u{2014} hand-maintained",
    );
    w(
        out,
        0,
        "// These builders contain complex logic that cannot be generated.",
    );
    w(
        out,
        0,
        "// Implement each custom_* function with the actual business logic.",
    );
}

fn gen_custom_impl(out: &mut String, b: &BuilderDecl) {
    let param_list = gen_param_list(&b.params);
    let generic_prefix = match &b.generic {
        Some(g) => format!("<{}>", g),
        None => String::new(),
    };
    w(
        out,
        0,
        &format!(
            "pub(crate) fn custom_{}{}({}) -> {} {{",
            b.name, generic_prefix, param_list, b.output_type
        ),
    );
    w(out, 1, "todo!(\"migrate from original s3_api module\")");
    w(out, 0, "}");
}

// ---------------------------------------------------------------------------
// Utilities
// ---------------------------------------------------------------------------

fn gen_param_list(params: &[(String, String)]) -> String {
    params
        .iter()
        .map(|(name, ty)| format!("{}: {}", name, ty))
        .collect::<Vec<_>>()
        .join(", ")
}

fn gen_arg_list(params: &[(String, String)]) -> String {
    params
        .iter()
        .map(|(name, _)| name.as_str())
        .collect::<Vec<_>>()
        .join(", ")
}

