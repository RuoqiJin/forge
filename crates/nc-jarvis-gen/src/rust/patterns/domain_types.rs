//! Domain Types code generator.
//!
//! Generates domain struct and enum definitions by delegating to atoms:
//! - `atoms::struct_def::gen_struct_def()` for structs
//! - `atoms::enum_def::gen_enum_def()` for enums
//!
//! This pattern has ZERO direct struct/enum/impl string generation.
//! All code shape comes from atoms — this file only maps IR → atom input.

use nc_jarvis_ir::rust::domain_types::*;

use crate::common::w;
use crate::rust::atoms::enum_def::{gen_enum_def, EnumDefInput, VariantDef};
use crate::rust::atoms::struct_def::{
    gen_struct_def, DeriveSet, FieldDef, StructDefInput, Visibility,
};

// ---------------------------------------------------------------------------
// Public entry point
// ---------------------------------------------------------------------------

pub fn generate_domain_types(decl: &DomainTypesDecl) -> String {
    let mut out = String::with_capacity(4096);

    gen_header(&mut out, decl);
    gen_imports(&mut out, decl);
    out.push('\n');

    // Enums first, then structs (conventional ordering)
    for e in &decl.enums {
        let code = gen_enum_from_decl(e);
        out.push_str(&code);
        out.push('\n');
    }

    for s in &decl.structs {
        let code = gen_struct_from_decl(s);
        out.push_str(&code);
        out.push('\n');
    }

    out
}

// ---------------------------------------------------------------------------
// Header + imports
// ---------------------------------------------------------------------------

fn gen_header(out: &mut String, decl: &DomainTypesDecl) {
    w(out, 0, "// \u{1f916} GENERATED BY FORGE - DO NOT EDIT");
    w(
        out,
        0,
        &format!(
            "// Source: .missiond/intent.lisp (domain-types {})",
            decl.target
        ),
    );
    w(out, 0, "// Pattern: domain-types");
    w(out, 0, "");
}

fn gen_imports(out: &mut String, decl: &DomainTypesDecl) {
    let has_serde = decl.structs.iter().any(|_| true) || decl.enums.iter().any(|_| true);
    if has_serde {
        w(out, 0, "use serde::{Deserialize, Serialize};");
    }
}

// ---------------------------------------------------------------------------
// Enum: IR → Atom input conversion
// ---------------------------------------------------------------------------

fn gen_enum_from_decl(e: &EnumDecl) -> String {
    let variants: Vec<VariantDef> = e
        .variants
        .iter()
        .map(|v| VariantDef {
            name: v.name.clone(),
            doc: v.doc.clone(),
            str_value: Some(v.str_value.clone()),
        })
        .collect();

    // Build DeriveSet: always Debug, Clone, PartialEq, Eq, Serialize, Deserialize
    // Plus Copy if e.copy
    let mut custom = vec!["Eq".into()];
    if e.copy {
        custom.push("Copy".into());
    }
    let derives = DeriveSet {
        debug: true,
        clone: true,
        serialize: true,
        deserialize: true,
        partial_eq: true,
        custom,
    };

    let input = EnumDefInput {
        name: e.name.clone(),
        variants,
        derives,
        // domain_types uses method style (as_str/from_str), not trait style (Display/FromStr)
        derive_display: false,
        derive_from_str: false,
        gen_as_str_method: e.gen_as_str,
        gen_from_str_method: e.gen_from_str,
        from_str_default: e.from_str_default.clone(),
        serde_rename_all: e.serde_rename_all.clone(),
        extra_enum_attrs: vec![],
        doc: e.doc.clone(),
    };

    gen_enum_def(&input)
}

// ---------------------------------------------------------------------------
// Struct: IR → Atom input conversion
// ---------------------------------------------------------------------------

fn gen_struct_from_decl(s: &StructDecl) -> String {
    let fields: Vec<FieldDef> = s
        .fields
        .iter()
        .map(|f| {
            // Determine serde_skip_serializing_if
            let serde_skip = if f.optional && f.skip_none {
                Some("Option::is_none".into())
            } else {
                None
            };

            // Determine serde_default vs serde_default_fn
            let (serde_default, serde_default_fn) = match f.default.as_deref() {
                Some("true") => (true, None),
                Some(val) => (false, Some(val.to_string())),
                None => (false, None),
            };

            FieldDef {
                name: f.name.clone(),
                rust_type: f.rust_type.clone(),
                visibility: Visibility::Pub,
                doc: f.doc.clone(),
                serde_rename: f.serde_rename.clone(),
                serde_default,
                serde_skip_serializing_if: serde_skip,
                serde_default_fn,
                extra_field_attrs: vec![],
            }
        })
        .collect();

    // Parse derives: if empty, use default [Debug, Clone, Serialize, Deserialize]
    let derives = if s.derives.is_empty() {
        DeriveSet::serde_both()
    } else {
        parse_derive_set(&s.derives)
    };

    let input = StructDefInput {
        name: s.name.clone(),
        fields,
        derives,
        doc: s.doc.clone(),
        serde_rename_all: s.serde_rename_all.clone(),
        extra_struct_attrs: vec![],
        default_impl: s.default_impl,
    };

    gen_struct_def(&input)
}

/// Parse a list of derive trait names into a DeriveSet.
fn parse_derive_set(derives: &[String]) -> DeriveSet {
    let mut set = DeriveSet {
        debug: false,
        clone: false,
        serialize: false,
        deserialize: false,
        partial_eq: false,
        custom: vec![],
    };

    for d in derives {
        match d.as_str() {
            "Debug" => set.debug = true,
            "Clone" => set.clone = true,
            "Serialize" => set.serialize = true,
            "Deserialize" => set.deserialize = true,
            "PartialEq" => set.partial_eq = true,
            other => set.custom.push(other.to_string()),
        }
    }

    set
}

// ---------------------------------------------------------------------------
// Tests
// ---------------------------------------------------------------------------

#[cfg(test)]
mod tests {
    use super::*;
    use nc_parser::SexpNode;

    fn parse_and_gen(input: &str) -> String {
        let sexp = SexpNode::parse_one(input).unwrap();
        let decl = DomainTypesDecl::from_sexp(&sexp).unwrap();
        generate_domain_types(&decl)
    }

    #[test]
    fn generates_basic_enum() {
        let output = parse_and_gen(
            r#"(domain-types :target "test.rs"
              (enum Color :as-str false :from-str false
                (variant Red)
                (variant Green)
                (variant Blue)))"#,
        );

        assert!(output.contains("GENERATED BY FORGE"));
        assert!(output.contains("use serde::{Deserialize, Serialize};"));
        assert!(output.contains("pub enum Color {"));
        assert!(output.contains("Red,"));
        assert!(output.contains("Green,"));
        assert!(output.contains("Blue,"));
        assert!(output.contains("Serialize"));
        assert!(output.contains("Deserialize"));
    }

    #[test]
    fn generates_enum_with_as_str_from_str() {
        let output = parse_and_gen(
            r#"(domain-types :target "test.rs"
              (enum Status
                :from-str-default Unknown
                (variant Unknown)
                (variant Active "active")
                (variant Inactive "inactive")))"#,
        );

        // as_str method (default on)
        assert!(output.contains("pub fn as_str(&self) -> &'static str {"));
        assert!(output.contains("Self::Active => \"active\","));
        assert!(output.contains("Self::Inactive => \"inactive\","));
        assert!(output.contains("Self::Unknown => \"unknown\","));

        // from_str method with default
        assert!(output.contains("pub fn from_str(s: &str) -> Option<Self>"));
        assert!(output.contains("\"active\" => Some(Self::Active),"));
        assert!(output.contains("_ => Some(Self::Unknown),"));

        // Should NOT have trait-style Display/FromStr
        assert!(!output.contains("impl std::fmt::Display"));
        assert!(!output.contains("impl std::str::FromStr"));
    }

    #[test]
    fn generates_enum_with_copy() {
        let output = parse_and_gen(
            r#"(domain-types :target "test.rs"
              (enum Flag :as-str false :from-str false
                (variant On)
                (variant Off)))"#,
        );

        assert!(output.contains("Copy"));
    }

    #[test]
    fn generates_basic_struct() {
        let output = parse_and_gen(
            r#"(domain-types :target "test.rs"
              (struct UserProfile
                (field name String)
                (field email String)))"#,
        );

        assert!(output.contains("pub struct UserProfile {"));
        assert!(output.contains("pub name: String,"));
        assert!(output.contains("pub email: String,"));
        assert!(output.contains("#[derive(Debug, Clone, Serialize, Deserialize)]"));
    }

    #[test]
    fn generates_struct_with_serde_attrs() {
        let output = parse_and_gen(
            r#"(domain-types :target "test.rs"
              (struct ApiResponse
                :serde-rename "camelCase"
                (field slot_id String :rename "slotId")
                (field data "Option<Value>" :optional true :skip-none true)
                (field limit i32 :default "true")))"#,
        );

        assert!(output.contains("#[serde(rename_all = \"camelCase\")]"));
        assert!(output.contains("#[serde(rename = \"slotId\")]"));
        assert!(output.contains("#[serde(skip_serializing_if = \"Option::is_none\")]"));
        assert!(output.contains("#[serde(default)]"));
    }

    #[test]
    fn generates_struct_with_default_impl() {
        let output = parse_and_gen(
            r#"(domain-types :target "test.rs"
              (struct Config
                :default "true"
                (field name String)
                (field count i32)))"#,
        );

        assert!(output.contains("impl Default for Config {"));
        assert!(output.contains("fn default() -> Self {"));
        assert!(output.contains("name: String::new(),"));
        assert!(output.contains("count: 0,"));
    }

    #[test]
    fn generates_struct_with_custom_derives() {
        let output = parse_and_gen(
            r#"(domain-types :target "test.rs"
              (struct HashableItem
                :derives (Debug Clone Hash Eq PartialEq)
                (field id String)))"#,
        );

        assert!(output.contains("#[derive(Debug, Clone, PartialEq, Hash, Eq)]"));
        let derive_line = output
            .lines()
            .find(|l| l.starts_with("#[derive("))
            .expect("derive line");
        assert!(!derive_line.contains("Serialize"));
        assert!(!derive_line.contains("Deserialize"));
    }

    #[test]
    fn generates_struct_with_default_fn() {
        let output = parse_and_gen(
            r#"(domain-types :target "test.rs"
              (struct Settings
                (field timeout i32 :default "default_timeout")))"#,
        );

        assert!(output.contains("#[serde(default = \"default_timeout\")]"));
    }

    #[test]
    fn generates_mixed_enums_and_structs() {
        let output = parse_and_gen(
            r#"(domain-types :target "test.rs"
              (enum Priority :as-str false :from-str false
                (variant Low)
                (variant High))
              (struct Task
                (field name String)
                (field priority String)))"#,
        );

        assert!(output.contains("pub enum Priority {"));
        assert!(output.contains("pub struct Task {"));
        let enum_pos = output.find("pub enum Priority").unwrap();
        let struct_pos = output.find("pub struct Task").unwrap();
        assert!(enum_pos < struct_pos);
    }

    #[test]
    fn generates_enum_with_doc() {
        let output = parse_and_gen(
            r#"(domain-types :target "test.rs"
              (enum Status :doc "Execution status" :as-str false :from-str false
                (variant Pending :doc "Waiting to start")
                (variant Done)))"#,
        );

        assert!(output.contains("/// Execution status"));
        assert!(output.contains("/// Waiting to start"));
    }

    #[test]
    fn generates_struct_with_field_doc() {
        let output = parse_and_gen(
            r#"(domain-types :target "test.rs"
              (struct User :doc "A registered user"
                (field name String :doc "Display name")
                (field email String)))"#,
        );

        assert!(output.contains("/// A registered user"));
        assert!(output.contains("/// Display name"));
    }

    #[test]
    fn brace_balance() {
        let output = parse_and_gen(
            r#"(domain-types :target "test.rs"
              (enum Status
                (variant A)
                (variant B)
                (variant C))
              (struct Data
                :default "true"
                (field x i32)
                (field y String)))"#,
        );

        let open = output.matches('{').count();
        let close = output.matches('}').count();
        assert_eq!(open, close, "unbalanced: {open} open vs {close} close");
    }

    #[test]
    fn enum_serde_rename_all() {
        let output = parse_and_gen(
            r#"(domain-types :target "test.rs"
              (enum Direction :serde-rename "snake_case" :as-str false :from-str false
                (variant North)
                (variant South)))"#,
        );

        assert!(output.contains("#[serde(rename_all = \"snake_case\")]"));
    }

    #[test]
    fn no_direct_struct_enum_string_generation() {
        let output = parse_and_gen(
            r#"(domain-types :target "test.rs"
              (enum E :as-str false :from-str false (variant A))
              (struct S (field x i32)))"#,
        );

        assert!(output.contains("pub enum E {"));
        assert!(output.contains("pub struct S {"));
    }
}
