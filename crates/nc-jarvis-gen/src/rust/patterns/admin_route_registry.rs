    #[test]
    fn generated_has_balanced_braces() {
        let decl = make_minimal_decl();
        let code = generate_admin_route_registry(&decl);
        let opens = code.chars().filter(|c| *c == '{').count();
        let closes = code.chars().filter(|c| *c == '}').count();
        assert_eq!(opens, closes, "unbalanced braces:\n{}", code);
    }

    #[test]
    fn generated_contains_handler_structs() {
        let decl = make_minimal_decl();
        let code = generate_admin_route_registry(&decl);
        assert!(code.contains("pub struct HealthCheckHandler {"));
        assert!(code.contains("pub struct AssumeRoleHandle {"));
    }

    #[test]
    fn generated_contains_register_functions() {
        let decl = make_minimal_decl();
        let code = generate_admin_route_registry(&decl);
        assert!(code.contains("pub fn register_health_route("));
        assert!(code.contains("pub fn register_admin_auth_route("));
    }

    #[test]
    fn generated_contains_coordinator() {
        let decl = make_minimal_decl();
        let code = generate_admin_route_registry(&decl);
        assert!(code.contains("pub fn make_admin_route("));
        assert!(code.contains("register_health_route(&mut r)?;"));
        assert!(code.contains("register_admin_auth_route(&mut r)?;"));
    }

    #[test]
    fn generated_contains_route_inserts() {
        let decl = make_minimal_decl();
        let code = generate_admin_route_registry(&decl);
        assert!(code.contains(
            "r.insert(Method::GET, \"/health\", AdminOperation(&HealthCheckHandler {}))?;"
        ));
        assert!(code.contains(
            "r.insert(Method::HEAD, \"/health\", AdminOperation(&HealthCheckHandler {}))?;"
        ));
        assert!(code.contains(
            "r.insert(Method::POST, \"/\", AdminOperation(&AssumeRoleHandle {}))?;"
        ));
    }

    #[test]
    fn generated_header_contains_counts() {
        let decl = make_minimal_decl();
        let code = generate_admin_route_registry(&decl);
        assert!(code.contains("Route groups: 2"));
        assert!(code.contains("Total routes: 3"));
        assert!(code.contains("Unique handlers: 2"));
    }

    #[test]
    fn sub_group_delegation() {
        let decl = AdminRouteRegistryDecl {
            name: "test".into(),
            coordinator: "make_route".into(),
            router_type: "Router".into(),
            groups: vec![
                RouteGroupDecl {
                    name: "parent".into(),
                    register_fn: "register_parent_route".into(),
                    module_path: "handlers::parent".into(),
                    routes: vec![],
                    sub_groups: vec!["child_a".into(), "child_b".into()],
                },
                RouteGroupDecl {
                    name: "child_a".into(),
                    register_fn: "register_child_a_route".into(),
                    module_path: "handlers::child_a".into(),
                    routes: vec![RouteDecl {
                        handler: "HandlerA".into(),
                        method: HttpMethod::Get,
                        path: "/a".into(),
                    }],
                    sub_groups: vec![],
                },
                RouteGroupDecl {
                    name: "child_b".into(),
                    register_fn: "register_child_b_route".into(),
                    module_path: "handlers::child_b".into(),
                    routes: vec![RouteDecl {
                        handler: "HandlerB".into(),
                        method: HttpMethod::Post,
                        path: "/b".into(),
                    }],
                    sub_groups: vec![],
                },
            ],
        };

        let code = generate_admin_route_registry(&decl);

        // Parent should delegate to children
        assert!(code.contains("register_child_a_route(r)?;"));
        assert!(code.contains("register_child_b_route(r)?;"));

        // Only parent should appear in coordinator (children are sub-groups)
        let coordinator_section = code
            .split("// --- Coordinator ---")
            .nth(1)
            .expect("coordinator section");
        assert!(coordinator_section.contains("register_parent_route(&mut r)?;"));
        assert!(!coordinator_section.contains("register_child_a_route(&mut r)?;"));
        assert!(!coordinator_section.contains("register_child_b_route(&mut r)?;"));
    }

