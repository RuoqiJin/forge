//! Admin Route Registry code generator.
//!
//! Generates **generated_routes.rs** containing:
//! - Handler struct definitions (empty unit structs)
//! - Route registration functions (`register_*_route`)
//! - Coordinator function (`make_admin_route`)
//!
//! Entry point: `generate_admin_route_registry(decl) -> String`

use nc_jarvis_ir::admin_route_registry::*;

use crate::rust::atoms::struct_def::{gen_struct_def, StructDefInput};
use crate::quarks::derive_attr::DeriveSet;

// ---------------------------------------------------------------------------
// Public entry point
// ---------------------------------------------------------------------------

/// Generate **generated_routes.rs** — all handler structs + register functions + coordinator.
pub fn generate_admin_route_registry(decl: &AdminRouteRegistryDecl) -> String {
    let mut out = String::with_capacity(16384);

    gen_header(&mut out, decl);
    out.push('\n');
    gen_handler_structs(&mut out, decl);
    out.push('\n');
    gen_register_functions(&mut out, decl);
    out.push('\n');
    gen_coordinator(&mut out, decl);

    out
}

// ---------------------------------------------------------------------------
// Header
// ---------------------------------------------------------------------------

fn gen_header(out: &mut String, decl: &AdminRouteRegistryDecl) {
    w(out, 0, "// \u{1f916} GENERATED BY FORGE - DO NOT EDIT");
    w(
        out,
        0,
        &format!(
            "// Source: .missiond/intent-admin-routes.lisp (admin-route-registry {})",
            decl.name
        ),
    );
    w(
        out,
        0,
        "// Pattern: admin-route-registry (Admin API route registration layer)",
    );
    w(
        out,
        0,
        &format!(
            "// Route groups: {} | Total routes: {} | Unique handlers: {}",
            decl.groups.len(),
            decl.total_routes(),
            decl.unique_handlers().len()
        ),
    );
    w(out, 0, "");
    w(
        out,
        0,
        "use crate::admin::router::{AdminOperation, S3Router};",
    );
    w(out, 0, "use crate::s3::routes::S3Route;");
    w(out, 0, "use hyper::Method;");
}

// ---------------------------------------------------------------------------
// Handler structs
// ---------------------------------------------------------------------------

fn gen_handler_structs(out: &mut String, decl: &AdminRouteRegistryDecl) {
    w(out, 0, "// --- Handler structs ---");
    w(out, 0, "");

    // Handler structs — struct_def atom (empty unit structs)
    for handler in decl.unique_handlers() {
        out.push_str(&gen_struct_def(&StructDefInput {
            name: handler,
            fields: vec![],
            derives: DeriveSet {
                debug: false,
                clone: false,
                serialize: false,
                deserialize: false,
                partial_eq: false,
                custom: vec![],
            },
            doc: None,
            serde_rename_all: None,
            extra_struct_attrs: vec![],
            default_impl: false,
        }));
    }
}

// ---------------------------------------------------------------------------
// Register functions
// ---------------------------------------------------------------------------

fn gen_register_functions(out: &mut String, decl: &AdminRouteRegistryDecl) {
    w(out, 0, "// --- Route registration functions ---");

    for group in &decl.groups {
        w(out, 0, "");
        gen_register_function(out, group);
    }
}

fn gen_register_function(out: &mut String, group: &RouteGroupDecl) {
    w(
        out,
        0,
        &format!(
            "pub fn {}(r: &mut S3Router<AdminOperation>) -> std::io::Result<()> {{",
            group.register_fn
        ),
    );

    // Sub-group delegations first
    for sub in &group.sub_groups {
        // Find the sub-group's register function name from context
        // We need to look it up, but since we're generating per-group, we use a convention
        w(
            out,
            1,
            &format!("{}(r)?;", sub_group_register_fn_name(sub)),
        );
    }

    if !group.sub_groups.is_empty() && !group.routes.is_empty() {
        w(out, 0, "");
    }

    // Direct route registrations
    for route in &group.routes {
        let method_ident = method_to_rust(&route.method);
        w(
            out,
            1,
            &format!(
                "r.insert(Method::{}, \"{}\", AdminOperation(&{} {{}}))?;",
                method_ident, route.path, route.handler
            ),
        );
    }

    if !group.sub_groups.is_empty() || !group.routes.is_empty() {
        w(out, 0, "");
    }

    w(out, 1, "Ok(())");
    w(out, 0, "}");
}

/// Derive the register function name for a sub-group by convention.
/// This finds the actual register_fn from the group declarations.
fn sub_group_register_fn_name(sub_group_name: &str) -> String {
    // Convention: register_{name}_route
    // But some have different names, so we use the standard convention
    // The actual lookup happens at codegen time from the full decl
    format!("register_{}_route", sub_group_name)
}

// ---------------------------------------------------------------------------
// Coordinator
// ---------------------------------------------------------------------------

fn gen_coordinator(out: &mut String, decl: &AdminRouteRegistryDecl) {
    w(out, 0, "// --- Coordinator ---");
    w(out, 0, "");
    w(
        out,
        0,
        &format!(
            "pub fn {}(console_enabled: bool) -> std::io::Result<impl S3Route> {{",
            decl.coordinator
        ),
    );
    w(
        out,
        1,
        &format!(
            "let mut r: {} = S3Router::new(console_enabled);",
            decl.router_type
        ),
    );
    w(out, 0, "");

    for group in decl.top_level_groups() {
        w(out, 1, &format!("{}(&mut r)?;", group.register_fn));
    }

    w(out, 0, "");
    w(out, 1, "Ok(r)");
    w(out, 0, "}");
    w(out, 0, "");
}

// ---------------------------------------------------------------------------
// Utilities
// ---------------------------------------------------------------------------

fn method_to_rust(method: &HttpMethod) -> &'static str {
    match method {
        HttpMethod::Get => "GET",
        HttpMethod::Post => "POST",
        HttpMethod::Put => "PUT",
        HttpMethod::Delete => "DELETE",
        HttpMethod::Head => "HEAD",
    }
}

fn w(out: &mut String, indent: usize, line: &str) {
    for _ in 0..indent {
        out.push_str("    ");
    }
    out.push_str(line);
    out.push('\n');
}

