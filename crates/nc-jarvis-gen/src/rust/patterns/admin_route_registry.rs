    /// Full integration test: read real Lisp -> IR -> codegen -> write to .forge-output/
    #[test]
    #[ignore] // requires local xiaojinpro-gateway checkout
    fn full_stamp_from_real_lisp() {
        let lisp_path = "fixtures/xjpfs/.missiond/intent-admin-routes.lisp";
        let lisp_src = match std::fs::read_to_string(lisp_path) {
            Ok(s) => s,
            Err(_) => return, // skip if file not available
        };
        let node = nc_parser::SexpNode::parse_one(&lisp_src).expect("Failed to parse S-EXP");
        let decl = nc_jarvis_ir::admin_route_registry::AdminRouteRegistryDecl::from_sexp(&node)
            .expect("Failed to lower to IR");

        // Verify IR counts
        assert!(
            decl.groups.len() >= 20,
            "expected >=20 groups, got {}",
            decl.groups.len()
        );
        assert!(
            decl.total_routes() >= 110,
            "expected >=110 routes, got {}",
            decl.total_routes()
        );

        // Generate
        let generated = generate_admin_route_registry(&decl);

        // Balanced braces
        let g_open = generated.chars().filter(|c| *c == '{').count();
        let g_close = generated.chars().filter(|c| *c == '}').count();
        assert_eq!(
            g_open, g_close,
            "generated_routes.rs unbalanced braces"
        );

        // Key assertions on generated code
        assert!(generated.contains("pub fn make_admin_route("));
        assert!(generated.contains("pub struct HealthCheckHandler {"));
        assert!(generated.contains("pub struct AssumeRoleHandle {"));
        assert!(generated.contains("register_health_route(&mut r)?;"));
        assert!(generated.contains("register_admin_auth_route(&mut r)?;"));
        assert!(generated.contains("register_site_replication_route(&mut r)?;"));

        // Verify sub-group delegation in user register
        assert!(generated.contains("register_account_info_route(r)?;"));
        assert!(generated.contains("register_user_lifecycle_route(r)?;"));

        // Write to .forge-output/admin/
        let output_dir =
            "fixtures/xjpfs/.forge-output/admin";
        std::fs::create_dir_all(output_dir).expect("create .forge-output/admin");
        std::fs::write(
            format!("{}/generated_routes.rs", output_dir),
            &generated,
        )
        .expect("write generated_routes.rs");

        eprintln!("=== ADMIN STAMP COMPLETE ===");
        eprintln!("generated_routes.rs: {} lines", generated.lines().count());
        eprintln!(
            "groups={}, routes={}, handlers={}",
            decl.groups.len(),
            decl.total_routes(),
            decl.unique_handlers().len()
        );
        eprintln!("Output: {}", output_dir);
    }
