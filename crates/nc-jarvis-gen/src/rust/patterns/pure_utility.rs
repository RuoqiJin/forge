//! Pure Utility code generator.
//!
//! Generates the "algorithm isolation chamber":
//! - A trait with pure function signatures (no &self)
//! - A stub struct with `todo!()` implementations
//! - A TDD test module skeleton with declared test cases
//!
//! Forge generates the SHELL. Human/LLM fills the LOGIC in custom.rs.
//!
//! ## Layer 2 Principle
//!
//! This file delegates impl block and trait generation to Layer 1 atoms.
//! Pure-utility traits use `has_self: false` in TraitMethodDef to omit `&self`.
//! Header/imports/tests remain as direct w() calls.

use nc_jarvis_ir::pure_utility::*;

use crate::rust::atoms::impl_block::{gen_impl_block, ImplBlockInput, MethodDef};
use crate::rust::atoms::trait_contract::{gen_trait_contract, TraitContractInput, TraitMethodDef};

// ---------------------------------------------------------------------------
// Public entry point
// ---------------------------------------------------------------------------

pub fn generate_pure_utility(decl: &PureUtilityDecl) -> String {
    let mut out = String::with_capacity(4096);

    gen_header(&mut out, decl);
    gen_imports(&mut out);
    out.push('\n');

    gen_trait(&mut out, decl);
    gen_stub(&mut out, decl);
    gen_tests(&mut out, decl);

    out
}

// ---------------------------------------------------------------------------
// Header + imports (direct w() calls — kept as-is per constraints)
// ---------------------------------------------------------------------------

fn gen_header(out: &mut String, decl: &PureUtilityDecl) {
    w(out, 0, "// \u{1f916} GENERATED BY FORGE - DO NOT EDIT");
    w(
        out,
        0,
        &format!(
            "// Source: .missiond/intent.lisp (pure-utility {})",
            decl.name
        ),
    );
    w(out, 0, "// Pattern: pure-utility (algorithm isolation chamber)");
    w(out, 0, "//");
    w(
        out,
        0,
        "// Implement the trait in custom.rs — only pure functions allowed.",
    );
    w(out, 0, "");
}

fn gen_imports(out: &mut String) {
    // Minimal imports — the trait is generic, consumer adds their own
    w(out, 0, "#[allow(unused_imports)]");
    w(out, 0, "use std::time::Duration;");
    w(out, 0, "");
}

// ---------------------------------------------------------------------------
// Trait contract (the core deliverable) — delegated to trait_contract atom
// ---------------------------------------------------------------------------

fn gen_trait(out: &mut String, decl: &PureUtilityDecl) {
    let trait_name = to_pascal_case(&decl.name);

    w(
        out,
        0,
        "// ═══════════════════════════════════════════════════════════",
    );
    w(
        out,
        0,
        "// \u{1f916} GENERATED CONTRACT — implement in custom.rs",
    );
    w(
        out,
        0,
        "// ═══════════════════════════════════════════════════════════",
    );
    w(out, 0, "");

    let methods: Vec<TraitMethodDef> = decl
        .fns
        .iter()
        .map(|f| TraitMethodDef {
            name: f.name.clone(),
            params: f.params.clone(),
            return_type: f.returns.clone(),
            is_async: false,
            doc: f.doc.clone(),
            has_default: false,
            has_self: false,
        })
        .collect();

    let trait_code = gen_trait_contract(&TraitContractInput {
        name: trait_name,
        doc: None,
        methods,
        is_async_trait: false,
    });
    out.push_str(&trait_code);
    w(out, 0, "");
}

// ---------------------------------------------------------------------------
// Stub implementation with todo!() — delegated to impl_block atom
// ---------------------------------------------------------------------------

fn gen_stub(out: &mut String, decl: &PureUtilityDecl) {
    let trait_name = to_pascal_case(&decl.name);
    let struct_name = format!("{trait_name}Impl");

    w(
        out,
        0,
        "// ═══════════════════════════════════════════════════════════",
    );
    w(
        out,
        0,
        "// Stub: replace todo!() in custom.rs with real logic",
    );
    w(
        out,
        0,
        "// ═══════════════════════════════════════════════════════════",
    );
    w(out, 0, "");
    // Unit struct — not a braced struct, so keep as direct w() call
    w(out, 0, &format!("pub struct {struct_name};"));
    w(out, 0, "");

    // Build methods for the impl block atom
    let methods: Vec<MethodDef> = decl
        .fns
        .iter()
        .map(|f| {
            // Add underscore prefix to suppress unused warnings in todo!() stubs
            let params_unused: Vec<String> = f
                .params
                .iter()
                .map(|(name, typ)| format!("_{name}: {typ}"))
                .collect();

            MethodDef {
                signature: format!(
                    "fn {}({}) -> {}",
                    f.name,
                    params_unused.join(", "),
                    f.returns
                ),
                body: format!("todo!(\"implement {} in custom.rs\")", f.name),
                doc: f.doc.clone(),
                attributes: vec![],
            }
        })
        .collect();

    let input = ImplBlockInput {
        type_name: struct_name,
        trait_name: Some(trait_name),
        methods,
    };

    out.push_str(&gen_impl_block(&input));
    w(out, 0, "");
}

// ---------------------------------------------------------------------------
// TDD test skeleton
// ---------------------------------------------------------------------------

fn gen_tests(out: &mut String, decl: &PureUtilityDecl) {
    let trait_name = to_pascal_case(&decl.name);
    let struct_name = format!("{trait_name}Impl");

    w(out, 0, "#[cfg(test)]");
    w(out, 0, "mod tests {");
    w(out, 1, "use super::*;");
    w(out, 0, "");

    for f in &decl.fns {
        if f.test_cases.is_empty() {
            // Generate a placeholder test even without declared cases
            let test_name = format!("test_{}", f.name);
            w(out, 1, "#[test]");
            w(out, 1, &format!("fn {test_name}() {{"));
            w(
                out,
                2,
                &format!(
                    "// TODO: add test cases for {}::{}",
                    struct_name, f.name
                ),
            );
            w(
                out,
                2,
                &format!("// {struct_name}::{}(...);", f.name),
            );
            w(out, 1, "}");
            w(out, 0, "");
        } else {
            for tc in &f.test_cases {
                let test_name = format!(
                    "test_{}_{}",
                    f.name,
                    tc.name.replace('-', "_")
                );
                w(out, 1, "#[test]");
                w(out, 1, &format!("fn {test_name}() {{"));

                if !tc.input.is_empty() {
                    w(
                        out,
                        2,
                        &format!(
                            "let result = {struct_name}::{}({});",
                            f.name, tc.input
                        ),
                    );
                } else {
                    w(
                        out,
                        2,
                        &format!(
                            "let result = {struct_name}::{}();",
                            f.name
                        ),
                    );
                }
                w(
                    out,
                    2,
                    &format!("assert_eq!(result, {});", tc.expected),
                );
                w(out, 1, "}");
                w(out, 0, "");
            }
        }
    }

    w(out, 0, "}");
}

// ---------------------------------------------------------------------------
// Utilities
// ---------------------------------------------------------------------------

use crate::quarks::ident::to_pascal_case;

fn w(out: &mut String, indent: usize, line: &str) {
    for _ in 0..indent {
        out.push_str("    ");
    }
    out.push_str(line);
    out.push('\n');
}

// ---------------------------------------------------------------------------
// Tests
// ---------------------------------------------------------------------------

#[cfg(test)]
mod tests {
    use super::*;
    use nc_parser::SexpNode;

    fn parse_and_gen(input: &str) -> String {
        let sexp = SexpNode::parse_one(input).unwrap();
        let decl = PureUtilityDecl::from_sexp(&sexp).unwrap();
        generate_pure_utility(&decl)
    }

    #[test]
    fn generates_trait_and_stub() {
        let output = parse_and_gen(
            r#"(pure-utility semantic-helpers
              :target "missiond-core/src/semantic/gen_helpers.rs"
              (fn detect_idle_prompt
                :params ((lines "&[&str]"))
                :returns bool
                :doc "Check if screen shows idle prompt")
              (fn extract_timer
                :params ((line "&str"))
                :returns "Option<Duration>"
                :doc "Extract timer pattern from line"))"#,
        );

        // Header
        assert!(output.contains("GENERATED BY FORGE"));
        assert!(output.contains("pure-utility semantic-helpers"));

        // Trait
        assert!(output.contains("pub trait SemanticHelpers {"));
        assert!(output.contains("fn detect_idle_prompt(lines: &[&str]) -> bool;"));
        assert!(output.contains("fn extract_timer(line: &str) -> Option<Duration>;"));
        assert!(output.contains("/// Check if screen shows idle prompt"));

        // Stub
        assert!(output.contains("pub struct SemanticHelpersImpl;"));
        assert!(output.contains("impl SemanticHelpers for SemanticHelpersImpl {"));
        assert!(output.contains("todo!(\"implement detect_idle_prompt in custom.rs\")"));
        assert!(output.contains("todo!(\"implement extract_timer in custom.rs\")"));

        // Tests
        assert!(output.contains("#[cfg(test)]"));
        assert!(output.contains("fn test_detect_idle_prompt()"));
        assert!(output.contains("fn test_extract_timer()"));

        // Brace balance
        let open = output.matches('{').count();
        let close = output.matches('}').count();
        assert_eq!(open, close, "unbalanced: {open} vs {close}");
    }

    #[test]
    fn generates_test_cases() {
        let output = parse_and_gen(
            r#"(pure-utility parser-helpers
              (fn is_spinner
                :params ((ch char))
                :returns bool
                :test-cases
                  ((case "spinner-dot" :input "'⠋'" :expected true)
                   (case "normal-char" :input "'A'" :expected false))))"#,
        );

        assert!(output.contains("pub trait ParserHelpers {"));
        assert!(output.contains("fn is_spinner(ch: char) -> bool;"));

        // Named test cases
        assert!(output.contains("fn test_is_spinner_spinner_dot()"));
        assert!(output.contains("ParserHelpersImpl::is_spinner('⠋')"));
        assert!(output.contains("assert_eq!(result, true)"));

        assert!(output.contains("fn test_is_spinner_normal_char()"));
        assert!(output.contains("ParserHelpersImpl::is_spinner('A')"));
        assert!(output.contains("assert_eq!(result, false)"));
    }

    #[test]
    fn pascal_case_conversion() {
        assert_eq!(to_pascal_case("semantic-helpers"), "SemanticHelpers");
        assert_eq!(to_pascal_case("math"), "Math");
        assert_eq!(
            to_pascal_case("multi-word-name"),
            "MultiWordName"
        );
    }

    #[test]
    fn no_self_in_trait_signatures() {
        let output = parse_and_gen(
            r#"(pure-utility math
              (fn add :params ((a i32) (b i32)) :returns i32))"#,
        );

        // Pure functions must NOT have &self
        assert!(!output.contains("&self"));
        assert!(output.contains("fn add(a: i32, b: i32) -> i32;"));
    }

    #[test]
    fn full_pattern_file_roundtrip() {
        // Read the MissionD pattern file
        let pattern_path = std::path::Path::new(env!("HOME"))
            .join("Projects/missiond/.missiond/intent-pure-utility.lisp");
        let src = match std::fs::read_to_string(&pattern_path) {
            Ok(s) => s,
            Err(_) => {
                eprintln!("  SKIP: missiond pattern file not found");
                return;
            }
        };

        let nodes = SexpNode::parse(&src).unwrap();
        let decls = nc_jarvis_ir::pure_utility::parse_pure_utilities(&nodes).unwrap();

        assert_eq!(decls.len(), 3, "expected 3 pure-utility declarations");
        assert_eq!(decls[0].name, "semantic-parsing");
        assert_eq!(decls[1].name, "string-helpers");
        assert_eq!(decls[2].name, "token-budget");

        // semantic-parsing has 6 functions
        assert_eq!(decls[0].fns.len(), 6);
        assert_eq!(decls[0].fns[0].name, "is_spinner_char");
        assert_eq!(decls[0].fns[0].test_cases.len(), 4);
        assert_eq!(decls[0].fns[5].name, "is_idle_prompt");

        // string-helpers has 2 functions
        assert_eq!(decls[1].fns.len(), 2);
        assert_eq!(decls[1].fns[0].name, "safe_byte_truncate");

        // token-budget has 2 functions
        assert_eq!(decls[2].fns.len(), 2);
        assert_eq!(decls[2].fns[0].name, "estimate_tokens");

        // Generate all and verify
        for decl in &decls {
            let output = generate_pure_utility(decl);
            let open = output.matches('{').count();
            let close = output.matches('}').count();
            assert_eq!(
                open, close,
                "{}: unbalanced braces ({open} vs {close})",
                decl.name
            );
            eprintln!(
                "  {} -> {} lines, {} fns, {} test cases",
                decl.name,
                output.lines().count(),
                decl.fns.len(),
                decl.fns.iter().map(|f| f.test_cases.len()).sum::<usize>()
            );
        }
    }

    #[test]
    fn multiple_functions_brace_balance() {
        let output = parse_and_gen(
            r#"(pure-utility big-module
              (fn alpha :params ((x f64)) :returns f64)
              (fn beta :params ((a i32) (b i32)) :returns bool)
              (fn gamma :returns "Vec<String>")
              (fn delta :params ((s "&str") (n usize)) :returns "&str"))"#,
        );

        let open = output.matches('{').count();
        let close = output.matches('}').count();
        assert_eq!(open, close, "unbalanced: {open} vs {close}");

        assert!(output.contains("pub trait BigModule {"));
        assert!(output.contains("fn alpha(x: f64) -> f64;"));
        assert!(output.contains("fn beta(a: i32, b: i32) -> bool;"));
        assert!(output.contains("fn gamma() -> Vec<String>;"));
        assert!(output.contains("fn delta(s: &str, n: usize) -> &str;"));
    }
}
