#[cfg(test)]
mod tests {
    use super::*;
    use nc_parser::SexpNode;

    fn parse_and_gen(input: &str) -> String {
        let sexp = SexpNode::parse_one(input).unwrap();
        let decl = WorkerDecl::from_sexp(&sexp).unwrap();
        generate_worker(&decl)
    }

    #[test]
    fn event_listener_generates_broadcast_loop() {
        let output = parse_and_gen(
            r#"(worker message-persister
              :pattern event-listener
              :struct MessagePersister
              :constructor start
              :deps ((storage "Arc<Storage>") (event_bus EventBus))
              (listens-to
                (UserMessageReceived :fields (session_id content))
                (TextComplete :fields (session_id content)))
              (trait MessagePersisterLogic
                (on-event UserMessageReceived
                  :params ((session_id Uuid) (content String))
                  :returns "()")
                (on-event TextComplete
                  :params ((session_id Uuid) (content String))
                  :returns "()"))
              (shutdown :on broadcast-close)
              (error-strategy log-and-continue))"#,
        );

        assert!(output.contains("GENERATED BY FORGE"));
        assert!(output.contains("pub struct MessagePersister"));
        assert!(output.contains("pub fn start("));
        assert!(output.contains("rx.recv().await"));
        assert!(output.contains("Event::UserMessageReceived"));
        assert!(output.contains("Event::TextComplete"));
        assert!(output.contains("event bus closed, shutting down"));
        assert!(output.contains("pub trait MessagePersisterLogic"));
        assert!(output.contains("async fn on_user_message_received"));
        assert!(output.contains("async fn on_text_complete"));

        // Brace balance
        let open = output.matches('{').count();
        let close = output.matches('}').count();
        assert_eq!(open, close, "unbalanced: {open} vs {close}");
    }

    #[test]
    fn cron_worker_generates_sleep_loop() {
        let output = parse_and_gen(
            r#"(worker git-watcher
              :pattern cron-worker
              :struct GitWatcher
              :deps ((event_tx "broadcast::Sender<Event>") (project_root PathBuf))
              (schedule :interval 5s :method sleep)
              (state (last_hash "Option<String>" :default None))
              (trait GitWatcherLogic
                (on-tick :params ((state "&mut GitWatcherState")) :returns "()"))
              (error-strategy silent-continue))"#,
        );

        assert!(output.contains("GENERATED BY FORGE"));
        assert!(output.contains("pub struct GitWatcher"));
        assert!(output.contains("pub struct GitWatcherState"));
        assert!(output.contains("Duration::from_secs(5)"));
        assert!(output.contains("tokio::time::sleep"));
        assert!(output.contains("pub trait GitWatcherLogic"));
        assert!(output.contains("async fn on_tick"));
        assert!(!output.contains("interval.tick")); // sleep, not interval
    }

    #[test]
    fn cron_worker_generates_interval_loop() {
        let output = parse_and_gen(
            r#"(worker extraction
              :pattern cron-worker
              :struct ExtractionWorker
              :deps ((storage "Arc<Storage>"))
              (schedule :interval 60s :method interval)
              (trait ExtractionLogic
                (on-tick :returns "()"))
              (error-strategy log-and-continue))"#,
        );

        assert!(output.contains("Duration::from_secs(60)"));
        assert!(output.contains("interval.tick().await"));
        assert!(output.contains("pub trait ExtractionLogic"));
    }

    #[test]
    fn full_pattern_file_roundtrip() {
        let manifest = std::env::var("CARGO_MANIFEST_DIR").unwrap();
        let pattern_path = std::path::Path::new(&manifest)
            .parent()
            .unwrap()
            .parent()
            .unwrap()
            .join("patterns/jarvis-workers.lisp");
        let src = std::fs::read_to_string(&pattern_path)
            .unwrap_or_else(|e| panic!("failed to read {}: {e}", pattern_path.display()));

        let nodes = SexpNode::parse(&src).unwrap();
        let workers = nc_jarvis_ir::worker::parse_workers(&nodes).unwrap();

        assert_eq!(workers.len(), 4, "expected 4 worker declarations");
        assert_eq!(workers[0].name, "message-persister");
        assert_eq!(workers[1].name, "git-watcher");
        assert_eq!(workers[2].name, "jsonl-watcher");
        assert_eq!(workers[3].name, "extraction-worker");

        // Generate all and check no panics
        for w in &workers {
            let output = generate_worker(w);
            let open = output.matches('{').count();
            let close = output.matches('}').count();
            assert_eq!(
                open, close,
                "{}: unbalanced braces ({open} vs {close})",
                w.name
            );
            eprintln!("  {} -> {} lines", w.name, output.lines().count());
        }
    }
}
