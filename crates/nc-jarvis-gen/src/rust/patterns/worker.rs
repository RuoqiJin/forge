//! Worker code generator.
//!
//! Generates async worker shells for two patterns:
//! - `event-listener`: `broadcast::Receiver` + match dispatch loop
//! - `cron-worker`: `tokio::time::interval/sleep` + tick dispatch loop
//!
//! Both use Generation Gap: generated shell calls trait methods for business logic.
//!
//! ## Layer 2 Principle
//!
//! This file delegates all struct/impl/match/trait generation to Layer 1 atoms.
//! Only header/imports remain as direct w() calls.

use nc_jarvis_ir::worker::*;

use crate::rust::atoms::impl_block::{gen_impl_block, ImplBlockInput, MethodDef};
use crate::rust::atoms::match_arm::{gen_match_expr, MatchArmDef, MatchExprInput};
use crate::rust::atoms::struct_def::{gen_struct_def, FieldDef, StructDefInput, Visibility};
use crate::rust::atoms::trait_contract::{gen_trait_contract, TraitContractInput, TraitMethodDef};

// ---------------------------------------------------------------------------
// Public entry point
// ---------------------------------------------------------------------------

pub fn generate_worker(decl: &WorkerDecl) -> String {
    let mut out = String::with_capacity(4096);

    gen_header(&mut out, decl);
    gen_imports(&mut out, decl);
    out.push('\n');

    // State struct (if any state fields)
    if !decl.state_fields.is_empty() {
        gen_state_struct(&mut out, decl);
    }

    // Main struct + constructor + run()
    gen_struct(&mut out, decl);
    gen_impl(&mut out, decl);

    // Trait contract (Generation Gap)
    if let Some(ref tr) = decl.trait_decl {
        gen_trait(&mut out, tr);
    }

    out
}

// ---------------------------------------------------------------------------
// Header + imports (direct w() calls — kept as-is per constraints)
// ---------------------------------------------------------------------------

fn gen_header(out: &mut String, decl: &WorkerDecl) {
    w(out, 0, "// \u{1f916} GENERATED BY FORGE - DO NOT EDIT");
    w(
        out,
        0,
        &format!(
            "// Source: patterns/jarvis-workers.lisp (worker {})",
            decl.name
        ),
    );
    w(out, 0, &format!("// Pattern: {:?}\n", decl.pattern));
}

fn gen_imports(out: &mut String, decl: &WorkerDecl) {
    w(out, 0, "use anyhow::Result;");

    // Event-listener needs EventBus types
    if decl.pattern == WorkerPattern::EventListener {
        w(out, 0, "use crate::event_bus::EventBus;");
        w(out, 0, "use crate::types::Event;");
        w(out, 0, "use tokio::sync::broadcast;");
    }

    // Cron-worker needs time
    if decl.pattern == WorkerPattern::CronWorker {
        w(out, 0, "use std::time::Duration;");
    }

    // Import dep types
    for dep in &decl.deps {
        if dep.rust_type.contains("Storage") {
            w(out, 0, "use crate::memory::storage::Storage;");
            w(out, 0, "use std::sync::Arc;");
        }
        if dep.rust_type.contains("SessionManager") {
            w(out, 0, "use crate::control::session::SessionManager;");
        }
        if dep.rust_type.contains("PathBuf") {
            w(out, 0, "use std::path::PathBuf;");
        }
        if dep.rust_type.contains("broadcast::Sender") {
            w(out, 0, "use crate::types::Event;");
            w(out, 0, "use tokio::sync::broadcast;");
        }
    }
}

// ---------------------------------------------------------------------------
// State struct — via struct_def atom + impl_block atom (Default impl)
// ---------------------------------------------------------------------------

fn gen_state_struct(out: &mut String, decl: &WorkerDecl) {
    let state_name = format!("{}State", decl.struct_name);

    // Struct definition via struct_def atom (no derives needed for state structs)
    let struct_code = gen_struct_def(&StructDefInput {
        name: state_name.clone(),
        fields: decl
            .state_fields
            .iter()
            .map(|sf| FieldDef {
                name: sf.name.clone(),
                rust_type: sf.rust_type.clone(),
                visibility: Visibility::Pub,
                doc: None,
                serde_rename: None,
                serde_default: false,
                serde_skip_serializing_if: None,
                serde_default_fn: None,
                extra_field_attrs: vec![],
            })
            .collect(),
        derives: crate::rust::atoms::struct_def::DeriveSet {
            debug: false,
            clone: false,
            serialize: false,
            deserialize: false,
            partial_eq: false,
            custom: vec![],
        },
        doc: None,
        serde_rename_all: None,
        extra_struct_attrs: vec![],
        default_impl: false,
    });
    // Strip derive line (empty derives produce no line, so this is safe)
    out.push_str(&struct_code);
    out.push('\n');

    // Default impl via impl_block atom
    let mut default_body_lines = vec!["Self {".to_string()];
    for sf in &decl.state_fields {
        let val = sf
            .default
            .as_deref()
            .or(sf.init_expr.as_deref())
            .unwrap_or("Default::default()");
        default_body_lines.push(format!("    {}: {},", sf.name, val));
    }
    default_body_lines.push("}".to_string());

    let default_impl = gen_impl_block(&ImplBlockInput {
        type_name: state_name,
        trait_name: Some("Default".into()),
        methods: vec![MethodDef {
            signature: "fn default() -> Self".into(),
            body: default_body_lines.join("\n"),
            doc: None,
            attributes: vec![],
        }],
    });
    out.push_str(&default_impl);
    out.push('\n');
}

// ---------------------------------------------------------------------------
// Main struct — via struct_def atom
// ---------------------------------------------------------------------------

fn gen_struct(out: &mut String, decl: &WorkerDecl) {
    let struct_code = gen_struct_def(&StructDefInput {
        name: decl.struct_name.clone(),
        fields: decl
            .deps
            .iter()
            .map(|dep| FieldDef {
                name: dep.name.clone(),
                rust_type: dep.rust_type.clone(),
                visibility: Visibility::PubCrate,
                doc: None,
                serde_rename: None,
                serde_default: false,
                serde_skip_serializing_if: None,
                serde_default_fn: None,
                extra_field_attrs: vec![],
            })
            .collect(),
        derives: crate::rust::atoms::struct_def::DeriveSet {
            debug: false,
            clone: false,
            serialize: false,
            deserialize: false,
            partial_eq: false,
            custom: vec![],
        },
        doc: None,
        serde_rename_all: None,
        extra_struct_attrs: vec![],
        default_impl: false,
    });
    out.push_str(&struct_code);
    out.push('\n');
}

// ---------------------------------------------------------------------------
// Impl: constructor + run() — via impl_block atom
// ---------------------------------------------------------------------------

fn gen_impl(out: &mut String, decl: &WorkerDecl) {
    let trait_nm = trait_name(decl);
    let mut methods = Vec::new();

    if decl.constructor == "start" {
        // Static start() pattern (spawns task internally)
        let params: Vec<String> = decl
            .deps
            .iter()
            .map(|d| format!("{}: {}", d.name, d.rust_type))
            .collect();

        let sig = format!(
            "pub fn start({}) where Self: {} + 'static",
            params.join(", "),
            trait_nm,
        );

        methods.push(MethodDef {
            signature: sig,
            body: build_start_body(decl).join("\n"),
            doc: None,
            attributes: vec![],
        });
    } else {
        // new() pattern (returns Self, caller spawns)
        let params: Vec<String> = decl
            .deps
            .iter()
            .map(|d| format!("{}: {}", d.name, d.rust_type))
            .collect();

        let mut new_body_lines = vec!["Self {".to_string()];
        for dep in &decl.deps {
            new_body_lines.push(format!("    {},", dep.name));
        }
        new_body_lines.push("}".to_string());

        methods.push(MethodDef {
            signature: format!("pub fn new({}) -> Self", params.join(", ")),
            body: new_body_lines.join("\n"),
            doc: None,
            attributes: vec![],
        });

        // run() method
        methods.push(MethodDef {
            signature: format!(
                "pub async fn run(self) -> Result<()> where Self: {}",
                trait_nm,
            ),
            body: build_run_body(decl).join("\n"),
            doc: None,
            attributes: vec![],
        });
    }

    let impl_code = gen_impl_block(&ImplBlockInput {
        type_name: decl.struct_name.clone(),
        trait_name: None,
        methods,
    });
    out.push_str(&impl_code);
    out.push('\n');
}

// ---------------------------------------------------------------------------
// Body builders — assemble Vec<String> for method bodies
// ---------------------------------------------------------------------------

fn build_start_body(decl: &WorkerDecl) -> Vec<String> {
    match decl.pattern {
        WorkerPattern::EventListener => build_event_listener_lines(decl, true),
        WorkerPattern::CronWorker => build_cron_lines(decl, true),
    }
}

fn build_run_body(decl: &WorkerDecl) -> Vec<String> {
    match decl.pattern {
        WorkerPattern::EventListener => build_event_listener_lines(decl, false),
        WorkerPattern::CronWorker => build_cron_lines(decl, false),
    }
}

/// Build the event-listener loop body as a Vec of lines (relative to method indent).
fn build_event_listener_lines(decl: &WorkerDecl, spawned: bool) -> Vec<String> {
    let self_ref = if spawned { "worker" } else { "&self" };
    let mut lines = Vec::new();

    if spawned {
        lines.push(format!("let worker = {} {{", decl.struct_name));
        for dep in &decl.deps {
            lines.push(format!("    {},", dep.name));
        }
        lines.push("};".into());
    }

    // Subscribe to event bus
    let bus_dep = decl
        .deps
        .iter()
        .find(|d| d.rust_type.contains("EventBus"))
        .map(|d| d.name.as_str())
        .unwrap_or("event_bus");

    if spawned {
        lines.push(format!("let mut rx = {bus_dep}.subscribe();"));
        lines.push("tokio::spawn(async move {".into());
    } else {
        lines.push(format!("let mut rx = self.{bus_dep}.subscribe();"));
    }

    // Build the event dispatch match expression via match_arm atom
    let event_match = build_event_dispatch_match(decl, self_ref);

    // Build the recv match (outer match on rx.recv().await)
    let recv_match = build_recv_match(decl, &event_match, spawned);

    // Indent the loop + recv_match based on spawned context
    let indent_prefix = if spawned { "    " } else { "" };

    lines.push(format!("{indent_prefix}loop {{"));
    for line in &recv_match {
        lines.push(format!("{indent_prefix}    {line}"));
    }
    lines.push(format!("{indent_prefix}}}"));

    if spawned {
        lines.push("});".into());
    } else {
        lines.push("Ok(())".into());
    }

    lines
}

/// Build the inner event dispatch match (match &event { ... }) via match_arm atom.
fn build_event_dispatch_match(decl: &WorkerDecl, self_ref: &str) -> String {
    let mut arms = Vec::new();

    for ev in &decl.listens_to {
        let fields = if ev.fields.is_empty() {
            "..".to_string()
        } else {
            ev.fields.join(", ")
        };

        let pattern = format!("Event::{} {{ {} }}", ev.event_name, fields);

        let mut body_str = String::new();
        // Find matching trait method
        if let Some(ref tr) = decl.trait_decl {
            if let Some(m) = tr.methods.iter().find(|m| m.trigger == ev.event_name) {
                let args: Vec<String> = m
                    .params
                    .iter()
                    .map(|(name, _typ)| format!("{}.clone()", name))
                    .collect();
                body_str = match decl.error_strategy {
                    ErrorStrategy::LogAndContinue => {
                        format!(
                            "if let Err(e) = {self_ref}.{}({}) {{ tracing::error!(\"{{}} error: {{e}}\", \"{}\"); }}",
                            m.name,
                            args.join(", "),
                            m.name
                        )
                    }
                    ErrorStrategy::SilentContinue => {
                        format!(
                            "let _ = {self_ref}.{}({});",
                            m.name,
                            args.join(", ")
                        )
                    }
                    ErrorStrategy::FailFast => {
                        format!("{self_ref}.{}({})?;", m.name, args.join(", "))
                    }
                };
            }
        }

        arms.push(MatchArmDef { pattern, body: body_str, doc: None });
    }

    // Generate the match at indent 0 — caller will re-indent
    let match_code = gen_match_expr(&MatchExprInput {
        subject: "&event".into(),
        arms,
        fallback: Some("// ignore other events".into()),
        indent: 0,
    });

    match_code
}

/// Build the outer rx.recv() match lines.
fn build_recv_match(decl: &WorkerDecl, event_match: &str, _spawned: bool) -> Vec<String> {
    let mut lines = Vec::new();

    lines.push("match rx.recv().await {".into());
    lines.push("    Ok(event) => {".into());

    // Embed the event dispatch match (indent each line by 2 extra levels)
    for line in event_match.lines() {
        if line.is_empty() {
            lines.push(String::new());
        } else {
            lines.push(format!("        {line}"));
        }
    }

    lines.push("    }".into());

    // Error handling
    lines.push("    Err(broadcast::error::RecvError::Lagged(n)) => {".into());
    lines.push(format!(
        "        tracing::warn!(\"{}: lagged {{n}} events\");",
        decl.name
    ));
    lines.push("    }".into());

    lines.push("    Err(broadcast::error::RecvError::Closed) => {".into());
    match decl.shutdown {
        ShutdownTrigger::BroadcastClose => {
            lines.push(format!(
                "        tracing::info!(\"{}: event bus closed, shutting down\");",
                decl.name
            ));
            lines.push("        break;".into());
        }
        ShutdownTrigger::None => {
            lines.push(format!(
                "        tracing::info!(\"{}: event bus closed\");",
                decl.name
            ));
            lines.push("        break;".into());
        }
    }
    lines.push("    }".into());
    lines.push("}".into());

    lines
}

/// Build the cron worker loop body as a Vec of lines.
fn build_cron_lines(decl: &WorkerDecl, spawned: bool) -> Vec<String> {
    let self_ref = if spawned { "worker" } else { "&self" };
    let sched = decl.schedule.as_ref().expect("cron-worker needs schedule");
    let mut lines = Vec::new();

    if spawned {
        lines.push(format!("let worker = {} {{", decl.struct_name));
        for dep in &decl.deps {
            lines.push(format!("    {},", dep.name));
        }
        lines.push("};".into());
        lines.push("tokio::spawn(async move {".into());
    }

    let indent_prefix = if spawned { "    " } else { "" };

    // State initialization
    if !decl.state_fields.is_empty() {
        let state_name = format!("{}State", decl.struct_name);
        lines.push(format!(
            "{indent_prefix}let mut state = {state_name}::default();"
        ));
    }

    // Init function
    if let Some(ref init) = decl.init {
        if let Some(ref doc) = init.doc {
            lines.push(format!("{indent_prefix}// {doc}"));
        }
        lines.push(format!(
            "{indent_prefix}if let Err(e) = {self_ref}.{}().await {{ tracing::error!(\"init failed: {{e}}\"); }}",
            init.fn_name
        ));
    }

    // Timer setup
    match sched.method {
        ScheduleMethod::Interval => {
            lines.push(format!(
                "{indent_prefix}let mut interval = tokio::time::interval(Duration::from_secs({}));",
                sched.interval_secs
            ));
            lines.push(format!("{indent_prefix}loop {{"));
            lines.push(format!("{indent_prefix}    interval.tick().await;"));
        }
        ScheduleMethod::Sleep => {
            lines.push(format!("{indent_prefix}loop {{"));
            lines.push(format!(
                "{indent_prefix}    tokio::time::sleep(Duration::from_secs({})).await;",
                sched.interval_secs
            ));
        }
    }

    // Dispatch to trait method
    if let Some(ref tr) = decl.trait_decl {
        if let Some(m) = tr.methods.iter().find(|m| m.trigger == "tick") {
            let state_arg = if !decl.state_fields.is_empty() {
                "&mut state"
            } else {
                ""
            };
            let call = if state_arg.is_empty() {
                format!("{self_ref}.{}().await", m.name)
            } else {
                format!("{self_ref}.{}({state_arg}).await", m.name)
            };

            match decl.error_strategy {
                ErrorStrategy::LogAndContinue => {
                    lines.push(format!(
                        "{indent_prefix}    if let Err(e) = {call} {{ tracing::warn!(\"{}: tick error: {{e}}\", \"{}\"); }}",
                        decl.name, m.name
                    ));
                }
                ErrorStrategy::SilentContinue => {
                    lines.push(format!("{indent_prefix}    let _ = {call};"));
                }
                ErrorStrategy::FailFast => {
                    lines.push(format!("{indent_prefix}    {call}?;"));
                }
            }
        }
    }

    lines.push(format!("{indent_prefix}}}"));

    if spawned {
        lines.push("});".into());
    } else {
        lines.push("#[allow(unreachable_code)]".into());
        lines.push("Ok(())".into());
    }

    lines
}

// ---------------------------------------------------------------------------
// Trait generation — via trait_contract atom
// ---------------------------------------------------------------------------

fn gen_trait(out: &mut String, tr: &TraitDecl) {
    let trait_code = gen_trait_contract(&TraitContractInput {
        name: tr.name.clone(),
        doc: Some("Implement in custom.rs".into()),
        is_async_trait: true,
        methods: tr
            .methods
            .iter()
            .map(|m| {
                TraitMethodDef {
                    name: m.name.clone(),
                    is_async: true,
                    params: m.params.clone(),
                    return_type: m.returns.clone(),
                    doc: None,
                    has_default: false,
                    has_self: true,
                }
            })
            .collect(),
    });
    out.push_str(&trait_code);
    out.push('\n');
}

// ---------------------------------------------------------------------------
// Utilities
// ---------------------------------------------------------------------------

fn trait_name(decl: &WorkerDecl) -> String {
    decl.trait_decl
        .as_ref()
        .map(|t| t.name.clone())
        .unwrap_or_else(|| format!("{}Logic", decl.struct_name))
}

fn w(out: &mut String, indent: usize, line: &str) {
    for _ in 0..indent {
        out.push_str("    ");
    }
    out.push_str(line);
    out.push('\n');
}

