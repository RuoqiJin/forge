//! MissionD Tool Definition generator (Layer 2 Pattern).
//!
//! Composes the `tool_schema` atom to generate MissionD-style tool definition files.
//! Unlike `mcp_tool.rs` (which generates Jarvis Module trait + dispatch + handle_tool),
//! this pattern generates ONLY the `definitions() -> Vec<ToolDefinition>` function
//! used by MissionD's mcp crate.
//!
//! ## Architecture
//! - Layer 1 atom: `atoms::tool_schema::gen_tool_definitions_file`
//! - This Layer 2: IR (McpModuleDecl) → atom input (ToolDefinitionsInput) → code string
//!
//! ## Output per module
//! One file like `crates/missiond-mcp/src/tools/compute/job.rs` containing:
//! ```text
//! // 🤖 GENERATED BY FORGE - DO NOT EDIT
//! use serde_json::json;
//! use crate::ToolDefinition;
//!
//! pub fn definitions() -> Vec<ToolDefinition> { vec![...] }
//! ```

use nc_jarvis_ir::mcp_tool::*;
use crate::quarks::type_map::from_ir_arg_type;
use crate::rust::atoms::tool_schema::{
    gen_tool_definitions_file, ToolDefinitionsInput, ToolParam, ToolSchemaInput,
};

/// Generate a MissionD tool definitions file from an McpModuleDecl.
///
/// Returns `(target_path, generated_code)` tuple.
/// target_path comes from the `:target` field in the Lisp declaration.
pub fn generate_missiond_tool(decl: &McpModuleDecl) -> String {
    let tools: Vec<ToolSchemaInput> = decl
        .tools
        .iter()
        .map(|tool| ToolSchemaInput {
            name: tool.name.clone(),
            description: tool.description.clone(),
            params: tool
                .args
                .iter()
                .map(|arg| ToolParam {
                    name: arg.name.clone(),
                    json_type: from_ir_arg_type(&arg.arg_type),
                    required: arg.required,
                    description: arg.description.clone(),
                    enum_values: arg.enum_values.clone(),
                    default: arg.default.clone(),
                })
                .collect(),
        })
        .collect();

    let input = ToolDefinitionsInput {
        module_name: decl.name.clone(),
        tools,
    };

    gen_tool_definitions_file(&input)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn make_test_decl() -> McpModuleDecl {
        McpModuleDecl {
            name: "compute/job".into(),
            struct_name: "JobModule".into(),
            target: Some("crates/missiond-mcp/src/tools/compute/job.rs".into()),
            deps: vec![],
            dep_trait: None,
            tools: vec![ToolDecl {
                name: "mission_job_poll".into(),
                description: "Poll async job status".into(),
                args: vec![
                    ArgDecl {
                        name: "job_id".into(),
                        arg_type: ArgType::String,
                        required: true,
                        description: Some("Job ID".into()),
                        enum_values: vec![],
                        default: None,
                    },
                    ArgDecl {
                        name: "action".into(),
                        arg_type: ArgType::String,
                        required: false,
                        description: None,
                        enum_values: vec!["poll".into(), "list".into(), "cancel".into()],
                        default: Some("poll".into()),
                    },
                ],
                returns: "Value".into(),
                dispatch_on: None,
                strict_args: false,
                events: vec![],
                validations: vec![],
            }],
        }
    }

    #[test]
    fn generates_definitions_file() {
        let code = generate_missiond_tool(&make_test_decl());
        assert!(code.contains("GENERATED BY FORGE"));
        assert!(code.contains("pub fn definitions() -> Vec<ToolDefinition>"));
        assert!(code.contains("\"mission_job_poll\""));
        assert!(code.contains("\"required\": [\"job_id\"]"));
        assert!(code.contains("\"enum\": [\"poll\", \"list\", \"cancel\"]"));
    }

    #[test]
    fn uses_correct_module_name_in_header() {
        let code = generate_missiond_tool(&make_test_decl());
        assert!(code.contains("module compute/job"));
    }
}
