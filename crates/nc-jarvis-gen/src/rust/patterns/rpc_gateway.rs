//! RPC Gateway code generator.
//!
//! Generates the "generalized interface layer":
//! - JSON-RPC 2.0 request/response/error types
//! - Transport read/write loop (newline-delimited JSON)
//! - Tool dispatch match statement
//! - Error code constants
//! - `pub trait RpcGatewayLogic` for hand-written handlers
//!
//! Forge generates the SHELL. Human/LLM fills the business logic in custom.rs.

use nc_jarvis_ir::rpc_gateway::*;

use crate::rust::atoms::impl_block::{gen_impl_block, ImplBlockInput, MethodDef};
use crate::rust::atoms::match_arm::{gen_match_expr, MatchArmDef, MatchExprInput};
use crate::rust::atoms::struct_def::{gen_struct_def, FieldDef, StructDefInput, Visibility};
use crate::rust::atoms::trait_contract::{gen_trait_contract, TraitContractInput, TraitMethodDef};
use crate::quarks::derive_attr::DeriveSet;

// ---------------------------------------------------------------------------
// Public entry point
// ---------------------------------------------------------------------------

pub fn generate_rpc_gateway(decl: &RpcGatewayDecl) -> String {
    let mut out = String::with_capacity(8192);

    gen_header(&mut out, decl);
    gen_imports(&mut out, decl);
    out.push('\n');

    gen_error_codes(&mut out, decl);
    gen_rpc_types(&mut out);
    gen_dispatch(&mut out, decl);
    gen_transport_loop(&mut out, decl);
    gen_trait(&mut out, decl);

    out
}

// ---------------------------------------------------------------------------
// Header + imports
// ---------------------------------------------------------------------------

fn gen_header(out: &mut String, decl: &RpcGatewayDecl) {
    w(out, 0, "// \u{1f916} GENERATED BY FORGE - DO NOT EDIT");
    w(
        out,
        0,
        &format!(
            "// Source: .missiond/intent.lisp (rpc-gateway {})",
            decl.name
        ),
    );
    w(out, 0, "// Pattern: rpc-gateway (generalized interface layer)");
    w(out, 0, "");
}

fn gen_imports(out: &mut String, decl: &RpcGatewayDecl) {
    w(out, 0, "use serde::{Deserialize, Serialize};");
    w(out, 0, "use serde_json::Value;");
    w(out, 0, "use anyhow::Result;");

    for t in &decl.transports {
        match t {
            Transport::Stdio => {
                w(out, 0, "use tokio::io::{AsyncBufReadExt, AsyncWriteExt, BufReader};");
            }
            Transport::Ipc => {
                w(out, 0, "#[cfg(unix)]");
                w(out, 0, "use tokio::net::UnixListener;");
                w(out, 0, "#[cfg(windows)]");
                w(out, 0, "use tokio::net::TcpListener;");
            }
            Transport::WebSocket => {
                w(out, 0, "use tokio_tungstenite::tungstenite::Message;");
            }
        }
    }
    w(out, 0, "");
}

// ---------------------------------------------------------------------------
// Error code constants
// ---------------------------------------------------------------------------

fn gen_error_codes(out: &mut String, decl: &RpcGatewayDecl) {
    if decl.error_codes.is_empty() {
        return;
    }

    w(out, 0, "pub mod error_codes {");
    for ec in &decl.error_codes {
        w(
            out,
            1,
            &format!(
                "pub const {}: &str = \"{}\";",
                ec.name, ec.value
            ),
        );
    }
    w(out, 0, "}");
    w(out, 0, "");
}

