fn gen_transport_loop(out: &mut String, decl: &RpcGatewayDecl) {
    for transport in &decl.transports {
        match transport {
            Transport::Stdio => gen_stdio_loop(out, decl),
            Transport::Ipc => gen_ipc_loop(out, decl),
            Transport::WebSocket => {
                // WS is structurally different; generate a comment placeholder
                w(out, 0, "// WebSocket transport: implement in custom.rs");
                w(
                    out,
                    0,
                    "// (WS uses frame-based messages, not newline-delimited JSON)",
                );
                w(out, 0, "");
            }
        }
    }
}

fn gen_stdio_loop(out: &mut String, decl: &RpcGatewayDecl) {
    let trait_name = to_pascal_case(&decl.name);

    w(
        out,
        0,
        &format!(
            "pub async fn run_stdio<H: {trait_name}>(handler: &H) -> Result<()> {{"
        ),
    );
    w(out, 1, "let stdin = tokio::io::stdin();");
    w(out, 1, "let mut stdout = tokio::io::stdout();");
    w(out, 1, "let mut reader = BufReader::new(stdin);");
    w(out, 1, "let mut line = String::new();");
    w(out, 0, "");
    w(out, 1, "loop {");
    w(out, 2, "line.clear();");
    w(out, 2, "let bytes = reader.read_line(&mut line).await?;");
    w(out, 2, "if bytes == 0 { break; }");
    w(out, 0, "");
    w(out, 2, "let trimmed = line.trim();");
    w(out, 2, "if trimmed.is_empty() { continue; }");
    w(out, 0, "");
    w(
        out,
        2,
        "let request: Request = match serde_json::from_str(trimmed) {",
    );
    w(out, 3, "Ok(r) => r,");
    w(out, 3, "Err(e) => {");
    w(
        out,
        4,
        "let resp = Response::from_error(RequestId::Null, RpcError::ParseError(Some(e.to_string())));",
    );
    w(
        out,
        4,
        "let json = serde_json::to_string(&resp)?;",
    );
    w(out, 4, "stdout.write_all(json.as_bytes()).await?;");
    w(out, 4, "stdout.write_all(b\"\\n\").await?;");
    w(out, 4, "stdout.flush().await?;");
    w(out, 4, "continue;");
    w(out, 3, "}");
    w(out, 2, "};");
    w(out, 0, "");

    // Dispatch based on method
    w(
        out,
        2,
        "let id = request.id.clone().unwrap_or(RequestId::Null);",
    );
    // Method dispatch — match_arm atom
    let mut method_arms: Vec<MatchArmDef> = decl.methods.iter().map(|method| {
        MatchArmDef {
            pattern: format!("\"{}\"", method.name),
            body: format!("handler.{}(id.clone(), request.params.unwrap_or(Value::Null)).await", method.handler),
            doc: None,
        }
    }).collect();

    // Fallback arm binds `other` for error reporting — use a named pattern, not `_`
    method_arms.push(MatchArmDef {
        pattern: "other".into(),
        body: "Response::from_error(id, RpcError::MethodNotFound(other.to_string()))".into(),
        doc: None,
    });

    w(out, 2, "let response =");
    let method_match = gen_match_expr(&MatchExprInput {
        subject: "request.method.as_str()".into(),
        arms: method_arms,
        fallback: None,
        indent: 2,
    });
    out.push_str(&method_match);
    w(out, 2, ";");
    w(out, 0, "");

    w(
        out,
        2,
        "let json = serde_json::to_string(&response)?;",
    );
    w(out, 2, "stdout.write_all(json.as_bytes()).await?;");
    w(out, 2, "stdout.write_all(b\"\\n\").await?;");
    w(out, 2, "stdout.flush().await?;");
    w(out, 1, "}");
    w(out, 1, "Ok(())");
    w(out, 0, "}");
    w(out, 0, "");
}

fn gen_ipc_loop(out: &mut String, _decl: &RpcGatewayDecl) {
    w(
        out,
        0,
        "// IPC transport: newline-delimited JSON over Unix socket / TCP loopback",
    );
    w(
        out,
        0,
        "pub async fn handle_ipc_message(message: &str) -> Result<String> {",
    );
    w(out, 1, "let request: Request = serde_json::from_str(message)");
    w(out, 2, ".map_err(|e| anyhow::anyhow!(\"parse error: {e}\"))?;");
    w(out, 1, "let id = request.id.clone().unwrap_or(RequestId::Null);");
    w(out, 1, "// Route to handler — implement in custom.rs");
    w(
        out,
        1,
        "let response = Response::from_error(id, RpcError::InternalError(\"not implemented\".into()));",
    );
    w(out, 1, "Ok(serde_json::to_string(&response)?)");
    w(out, 0, "}");
    w(out, 0, "");
}

// ---------------------------------------------------------------------------
// Trait generation (Generation Gap)
// ---------------------------------------------------------------------------

fn gen_trait(out: &mut String, decl: &RpcGatewayDecl) {
    let trait_name = to_pascal_case(&decl.name);

    w(
        out,
        0,
        "// ═══════════════════════════════════════════════════════════",
    );
    w(
        out,
        0,
        "// \u{1f916} GENERATED CONTRACT — implement in custom.rs",
    );
    w(
        out,
        0,
        "// ═══════════════════════════════════════════════════════════",
    );
    w(out, 0, "");

    // Build trait methods from method handlers and dispatch groups — trait_contract atom
    let mut trait_methods = Vec::new();

    for method in &decl.methods {
        trait_methods.push(TraitMethodDef {
            name: method.handler.clone(),
            params: vec![
                ("id".into(), "RequestId".into()),
                ("params".into(), "Value".into()),
            ],
            return_type: "Response".into(),
            is_async: true,
            doc: method.description.clone(),
            has_default: false,
            has_self: true,
        });
    }

    for group in &decl.dispatch_groups {
        trait_methods.push(TraitMethodDef {
            name: format!("handle_{}", group.module_name),
            params: vec![
                ("tool_name".into(), "&str".into()),
                ("args".into(), "Value".into()),
            ],
            return_type: "Result<Value>".into(),
            is_async: true,
            doc: Some(format!("Handle tools in the '{}' domain", group.module_name)),
            has_default: false,
            has_self: true,
        });
    }

    // Generate trait body with atom (is_async_trait=false — we handle the attribute manually
    // to preserve the `async_trait::async_trait` path form and `: Send + Sync` supertrait)
    let mut trait_code = gen_trait_contract(&TraitContractInput {
        name: trait_name.clone(),
        doc: None,
        methods: trait_methods,
        is_async_trait: false,
    });

    // Insert supertrait bound and async_trait attribute
    trait_code = trait_code.replace(
        &format!("pub trait {} {{", trait_name),
        &format!("#[async_trait::async_trait]\npub trait {}: Send + Sync {{", trait_name),
    );

    out.push_str(&trait_code);
    w(out, 0, "");
}

// ---------------------------------------------------------------------------
// Utilities
