//! Domain Engine code generator.
//!
//! Generates the "domain engine shell" — the thinnest possible wrapper:
//! - Struct with injected dependencies as fields
//! - `new()` constructor accepting all deps
//! - `pub trait EngineLogic` with exported method signatures
//!
//! ZERO internal logic. The "brain" lives 100% in custom.rs.
//!
//! ## Layer 2 Principle
//!
//! This file delegates struct/impl/trait generation to Layer 1 atoms.
//! Only header/imports remain as direct w() calls.

use nc_jarvis_ir::domain_engine::*;

use crate::rust::atoms::impl_block::{gen_impl_block, ImplBlockInput, MethodDef};
use crate::rust::atoms::struct_def::{gen_struct_def, FieldDef, StructDefInput, Visibility};
use crate::rust::atoms::trait_contract::{gen_trait_contract, TraitContractInput, TraitMethodDef};
use crate::quarks::derive_attr::DeriveSet;

// ---------------------------------------------------------------------------
// Public entry point
// ---------------------------------------------------------------------------

pub fn generate_domain_engine(decl: &DomainEngineDecl) -> String {
    let mut out = String::with_capacity(4096);

    gen_header(&mut out, decl);
    gen_imports(&mut out, decl);
    out.push('\n');
    gen_struct(&mut out, decl);
    gen_constructor(&mut out, decl);
    gen_trait(&mut out, decl);

    out
}

// ---------------------------------------------------------------------------
// Header + imports (direct w() calls — kept as-is per constraints)
// ---------------------------------------------------------------------------

fn gen_header(out: &mut String, decl: &DomainEngineDecl) {
    w(out, 0, "// \u{1f916} GENERATED BY FORGE - DO NOT EDIT");
    w(
        out,
        0,
        &format!(
            "// Source: .missiond/intent.lisp (domain-engine {})",
            decl.name
        ),
    );
    w(out, 0, "// Pattern: domain-engine (zero internal logic)");
    w(out, 0, "//");
    w(
        out,
        0,
        "// Implement EngineLogic trait in custom.rs — all business logic lives there.",
    );
    w(out, 0, "");
}

fn gen_imports(out: &mut String, decl: &DomainEngineDecl) {
    w(out, 0, "use anyhow::Result;");

    // Check if any export is async
    let has_async = decl.exports.iter().any(|e| e.is_async);
    if has_async {
        w(out, 0, "use async_trait::async_trait;");
    }
    w(out, 0, "");
}

// ---------------------------------------------------------------------------
// Struct definition — delegated to struct_def atom
// ---------------------------------------------------------------------------

fn gen_struct(out: &mut String, decl: &DomainEngineDecl) {
    let mut fields: Vec<FieldDef> = Vec::new();

    // Dependencies as pub(crate) fields
    for dep in &decl.deps {
        fields.push(FieldDef {
            name: dep.name.clone(),
            rust_type: dep.rust_type.clone(),
            visibility: Visibility::PubCrate,
            doc: None,
            serde_rename: None,
            serde_default: false,
            serde_skip_serializing_if: None,
            serde_default_fn: None,
            extra_field_attrs: vec![],
        });
    }

    // State fields
    for sf in &decl.state {
        fields.push(FieldDef {
            name: sf.name.clone(),
            rust_type: sf.rust_type.clone(),
            visibility: Visibility::PubCrate,
            doc: None,
            serde_rename: None,
            serde_default: false,
            serde_skip_serializing_if: None,
            serde_default_fn: None,
            extra_field_attrs: vec![],
        });
    }

    let input = StructDefInput {
        name: decl.struct_name.clone(),
        fields,
        derives: DeriveSet {
            debug: false,
            clone: false,
            serialize: false,
            deserialize: false,
            partial_eq: false,
            custom: vec![],
        },
        doc: None,
        serde_rename_all: None,
        extra_struct_attrs: vec![],
        default_impl: false,
    };

    out.push_str(&gen_struct_def(&input));
    w(out, 0, "");
}

// ---------------------------------------------------------------------------
// Constructor — delegated to impl_block atom
// ---------------------------------------------------------------------------

fn gen_constructor(out: &mut String, decl: &DomainEngineDecl) {
    // Build parameter list (only deps, state uses defaults)
    let params: Vec<String> = decl
        .deps
        .iter()
        .map(|d| format!("{}: {}", d.name, d.rust_type))
        .collect();

    // Build constructor body
    let mut body_lines = Vec::new();
    body_lines.push("Self {".to_string());
    for dep in &decl.deps {
        body_lines.push(format!("    {},", dep.name));
    }
    for sf in &decl.state {
        let val = sf.default.as_deref().unwrap_or("Default::default()");
        body_lines.push(format!("    {}: {},", sf.name, val));
    }
    body_lines.push("}".to_string());

    let input = ImplBlockInput {
        type_name: decl.struct_name.clone(),
        trait_name: None,
        methods: vec![MethodDef {
            signature: format!("pub fn new({}) -> Self", params.join(", ")),
            body: body_lines.join("\n"),
            doc: None,
            attributes: vec![],
        }],
    };

    out.push_str(&gen_impl_block(&input));
    w(out, 0, "");
}

// ---------------------------------------------------------------------------
// Trait contract (Generation Gap) — delegated to trait_contract atom
// ---------------------------------------------------------------------------

fn gen_trait(out: &mut String, decl: &DomainEngineDecl) {
    let trait_name = format!("{}Logic", decl.struct_name);
    let has_async = decl.exports.iter().any(|e| e.is_async);

    w(
        out,
        0,
        "// ═══════════════════════════════════════════════════════════",
    );
    w(
        out,
        0,
        "// \u{1f916} GENERATED CONTRACT — implement in custom.rs",
    );
    w(
        out,
        0,
        "// ═══════════════════════════════════════════════════════════",
    );
    w(out, 0, "");

    let methods: Vec<TraitMethodDef> = decl
        .exports
        .iter()
        .map(|exp| TraitMethodDef {
            name: exp.name.clone(),
            params: exp.params.clone(),
            return_type: exp.returns.clone(),
            is_async: exp.is_async,
            doc: exp.doc.clone(),
            has_default: false,
            has_self: true,
        })
        .collect();

    let input = TraitContractInput {
        name: trait_name,
        doc: None,
        methods,
        is_async_trait: has_async,
    };

    out.push_str(&gen_trait_contract(&input));
    w(out, 0, "");
}

// ---------------------------------------------------------------------------
// Utilities
// ---------------------------------------------------------------------------

fn w(out: &mut String, indent: usize, line: &str) {
    for _ in 0..indent {
        out.push_str("    ");
    }
    out.push_str(line);
    out.push('\n');
}

// ---------------------------------------------------------------------------
// Tests
