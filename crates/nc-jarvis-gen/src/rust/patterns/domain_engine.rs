#[cfg(test)]
mod tests {
    use super::*;
    use nc_parser::SexpNode;

    fn parse_and_gen(input: &str) -> String {
        let sexp = SexpNode::parse_one(input).unwrap();
        let decl = DomainEngineDecl::from_sexp(&sexp).unwrap();
        generate_domain_engine(&decl)
    }

    #[test]
    fn generates_struct_and_constructor() {
        let output = parse_and_gen(
            r#"(domain-engine slot-orchestrator
              :struct SlotOrchestrator
              (depends-on
                (db "DbExecutor")
                (pty_manager "Arc<PTYManager>"))
              (state
                (agents "HashMap<String, AgentHandle>" :default "HashMap::new()"))
              (exports
                (fn spawn :params ((slot_id "&str")) :returns "Result<()>")))"#,
        );

        assert!(output.contains("GENERATED BY FORGE"));
        assert!(output.contains("pub struct SlotOrchestrator {"));
        assert!(output.contains("pub(crate) db: DbExecutor,"));
        assert!(output.contains("pub(crate) pty_manager: Arc<PTYManager>,"));
        assert!(output.contains("pub(crate) agents: HashMap<String, AgentHandle>,"));

        // Constructor
        assert!(output.contains("pub fn new(db: DbExecutor, pty_manager: Arc<PTYManager>) -> Self {"));
        assert!(output.contains("agents: HashMap::new(),"));
    }

    #[test]
    fn generates_trait_contract() {
        let output = parse_and_gen(
            r#"(domain-engine llm-gateway
              :struct LlmGateway
              (depends-on (sonnet "SonnetGateway") (gemini "GeminiGateway"))
              (exports
                (fn route_request
                  :params ((prompt "&str") (model "&str"))
                  :returns "Result<String>"
                  :doc "Route an LLM request to the best provider")
                (fn estimate_cost
                  :params ((tokens usize))
                  :returns f64
                  :async false
                  :doc "Estimate cost for given token count")))"#,
        );

        assert!(output.contains("#[async_trait]"));
        assert!(output.contains("pub trait LlmGatewayLogic {"));
        assert!(output.contains("/// Route an LLM request to the best provider"));
        assert!(output.contains("async fn route_request(&self, prompt: &str, model: &str) -> Result<String>;"));
        assert!(output.contains("/// Estimate cost for given token count"));
        assert!(output.contains("fn estimate_cost(&self, tokens: usize) -> f64;"));
        // estimate_cost is sync — no async keyword
        assert!(!output.contains("async fn estimate_cost"));
    }

    #[test]
    fn brace_balance() {
        let output = parse_and_gen(
            r#"(domain-engine complex-engine
              :struct ComplexEngine
              (depends-on (a "A") (b "B") (c "C"))
              (state (x "X" :default "X::default()") (y "Y"))
              (exports
                (fn alpha :returns "Result<()>")
                (fn beta :params ((p i32)) :returns bool :async false)
                (fn gamma :params ((a "&str") (b "&str")) :returns "Result<String>")))"#,
        );

        let open = output.matches('{').count();
        let close = output.matches('}').count();
        assert_eq!(open, close, "unbalanced: {open} vs {close}");
    }

    #[test]
    fn minimal_engine_no_deps() {
        let output = parse_and_gen(
            r#"(domain-engine simple
              (exports (fn run :returns "Result<()>")))"#,
        );

        assert!(output.contains("pub struct Simple {"));
        assert!(output.contains("pub fn new() -> Self {"));
        assert!(output.contains("pub trait SimpleLogic {"));
        assert!(output.contains("async fn run(&self) -> Result<()>;"));
    }
}
