//! MCP Tool code generator (Layer 2 Pattern).
//!
//! Composes atomic codegen functions to generate per-module:
//! - Struct + new() — via `atoms::struct_def` + `atoms::di_field`
//! - tools() -> Vec<ToolSchema> — via `atoms::tool_schema`
//! - handle_tool() dispatch + arg extraction — via `atoms::arg_extract`
//! - McpXxxLogic trait (Generation Gap)
//!
//! ## Layer 2 Principle
//!
//! This file does NOT contain any string-building logic for structs, schemas,
//! or arg extraction. It delegates to Layer 1 atoms and assembles the results.

use nc_jarvis_ir::mcp_tool::*;

use crate::quarks::type_map::from_ir_arg_type;
use crate::quarks::ident::swap_prefix;
use crate::rust::atoms::w;
use crate::rust::atoms::struct_def::{gen_struct_def, DeriveSet, FieldDef, StructDefInput, Visibility};
use crate::rust::atoms::tool_schema::{gen_tool_schema, ToolParam, ToolSchemaInput};
use crate::rust::atoms::arg_extract::{gen_arg_extract, ArgExtractInput};

// ---------------------------------------------------------------------------
// Public entry point
// ---------------------------------------------------------------------------

pub fn generate_mcp_module(decl: &McpModuleDecl) -> String {
    let mut out = String::with_capacity(8192);

    gen_header(&mut out, decl);
    gen_imports(&mut out, decl);
    out.push('\n');

    // Struct via atom
    let struct_code = gen_struct_def(&StructDefInput {
        name: decl.struct_name.clone(),
        fields: decl
            .deps
            .iter()
            .map(|d| FieldDef {
                name: d.name.clone(),
                rust_type: d.rust_type.clone(),
                visibility: Visibility::PubCrate,
                doc: None,
                serde_rename: None,
                serde_default: false,
                serde_skip_serializing_if: None,
                serde_default_fn: None,
                extra_field_attrs: vec![],
            })
            .collect(),
        derives: DeriveSet::default(),
        doc: None,
        serde_rename_all: None,
        extra_struct_attrs: vec![],
        default_impl: false,
    });
    // struct-def atom generates derive, but MCP modules don't need it
    // Strip the derive line for this use case
    for line in struct_code.lines() {
        if !line.starts_with("#[derive") {
            out.push_str(line);
            out.push('\n');
        }
    }
    out.push('\n');

    gen_impl(&mut out, decl);

    // Trait contract
    gen_trait(&mut out, decl);

    out
}

// ---------------------------------------------------------------------------
// Header + imports
// ---------------------------------------------------------------------------

fn gen_header(out: &mut String, decl: &McpModuleDecl) {
    w(out, 0, "// \u{1f916} GENERATED BY FORGE - DO NOT EDIT");
    w(
        out,
        0,
        &format!(
            "// Source: patterns/jarvis-mcp-tools.lisp (mcp-module {})",
            decl.name
        ),
    );
    out.push('\n');
}

fn gen_imports(out: &mut String, decl: &McpModuleDecl) {
    w(out, 0, "use crate::module::Module;");
    w(out, 0, "use crate::types::{ModuleContext, ToolSchema};");
    w(out, 0, "use anyhow::Result;");
    w(out, 0, "use async_trait::async_trait;");
    w(out, 0, "use serde_json::{json, Value};");
    w(out, 0, "use std::sync::Arc;");

    for dep in &decl.deps {
        if dep.rust_type.contains("Storage") {
            w(out, 0, "use crate::memory::storage::Storage;");
        }
        if dep.rust_type.contains("broadcast::Sender") {
            w(out, 0, "use tokio::sync::broadcast;");
        }
    }
    if let Some(ref tr) = decl.dep_trait {
        if tr == "StorageCustomLogic" {
            w(out, 0, "use crate::memory::storage::StorageCustomLogic;");
        }
    }
}

// ---------------------------------------------------------------------------
// Impl: new() + Module trait
// ---------------------------------------------------------------------------

fn gen_impl(out: &mut String, decl: &McpModuleDecl) {
    // new()
    w(out, 0, &format!("impl {} {{", decl.struct_name));
    let params: Vec<String> = decl
        .deps
        .iter()
        .map(|d| format!("{}: {}", d.name, d.rust_type))
        .collect();
    w(
        out,
        1,
        &format!("pub fn new({}) -> Self {{", params.join(", ")),
    );
    w(out, 2, "Self {");
    for dep in &decl.deps {
        w(out, 3, &format!("{},", dep.name));
    }
    w(out, 2, "}");
    w(out, 1, "}");
    w(out, 0, "}\n");

    // Module trait impl
    w(out, 0, "#[async_trait]");
    w(out, 0, "#[allow(unused_variables)]");
    w(out, 0, &format!("impl Module for {} {{", decl.struct_name));

    // name()
    w(out, 1, "fn name(&self) -> &str {");
    w(out, 2, &format!("\"{}\"", decl.name));
    w(out, 1, "}\n");

    // tools() — delegates to tool-schema atom
    gen_tools_method(out, decl);

    // handle_tool() — delegates to arg-extract atom
    gen_handle_tool(out, decl);

    w(out, 0, "}\n");
}

// ---------------------------------------------------------------------------
// tools() method — uses tool-schema atom
// ---------------------------------------------------------------------------

fn gen_tools_method(out: &mut String, decl: &McpModuleDecl) {
    w(out, 1, "fn tools(&self) -> Vec<ToolSchema> {");
    w(out, 2, "vec![");

    for tool in &decl.tools {
        // Convert IR args to atom's ToolParam format
        let params: Vec<ToolParam> = tool
            .args
            .iter()
            .map(|arg| ToolParam {
                name: arg.name.clone(),
                json_type: from_ir_arg_type(&arg.arg_type),
                required: arg.required,
                description: arg.description.clone(),
                enum_values: arg.enum_values.clone(),
                default: arg.default.clone(),
            })
            .collect();

        // Use tool-schema atom to generate the JSON Schema
        let schema_input = ToolSchemaInput {
            name: tool.name.clone(),
            description: tool.description.clone(),
            params,
        };
        let _schema_fragment = gen_tool_schema(&schema_input);

        // Convert ToolDefinition format to ToolSchema format
        // The atom generates ToolDefinition::new(...), but Jarvis uses ToolSchema { ... }
        // We adapt the output here at the pattern level
        w(out, 3, "ToolSchema {");
        w(out, 4, &format!("name: \"{}\".into(),", tool.name));
        w(
            out,
            4,
            &format!("description: \"{}\".into(),", tool.description),
        );

        // Build JSON schema using the same logic as the atom (reuse param conversion)
        w(out, 4, "input_schema: json!({");
        w(out, 5, "\"type\": \"object\",");

        let required: Vec<&str> = tool
            .args
            .iter()
            .filter(|a| a.required)
            .map(|a| a.name.as_str())
            .collect();
        if !required.is_empty() {
            let req_json: Vec<String> = required.iter().map(|r| format!("\"{}\"", r)).collect();
            w(
                out,
                5,
                &format!("\"required\": [{}],", req_json.join(", ")),
            );
        }

        w(out, 5, "\"properties\": {");
        for (i, arg) in tool.args.iter().enumerate() {
            let comma = if i < tool.args.len() - 1 { "," } else { "" };
            let mut parts = vec![format!(
                "\"type\": \"{}\"",
                from_ir_arg_type(&arg.arg_type).as_json_str()
            )];
            if let Some(ref desc) = arg.description {
                parts.push(format!("\"description\": \"{}\"", desc));
            }
            if !arg.enum_values.is_empty() {
                let vals: Vec<String> =
                    arg.enum_values.iter().map(|v| format!("\"{}\"", v)).collect();
                parts.push(format!("\"enum\": [{}]", vals.join(", ")));
            }
            w(
                out,
                6,
                &format!(
                    "\"{}\": {{ {} }}{}",
                    arg.name,
                    parts.join(", "),
                    comma
                ),
            );
        }
        w(out, 5, "}");
        w(out, 4, "}),");
        w(out, 3, "},");
    }

    w(out, 2, "]");
    w(out, 1, "}\n");
}

// ---------------------------------------------------------------------------
// handle_tool() — uses arg-extract atom
// ---------------------------------------------------------------------------

fn gen_handle_tool(out: &mut String, decl: &McpModuleDecl) {
    w(
        out,
        1,
        "async fn handle_tool(&self, name: &str, args: Value, ctx: &ModuleContext) -> Result<Value> {",
    );
    w(out, 2, "match name {");

    for tool in &decl.tools {
        w(out, 3, &format!("\"{}\" => {{", tool.name));

        // Convert IR args to atom's ToolParam format and generate extraction
        let params: Vec<ToolParam> = tool
            .args
            .iter()
            .map(|arg| {
                let mut tp = ToolParam {
                    name: arg.name.clone(),
                    json_type: from_ir_arg_type(&arg.arg_type),
                    required: arg.required && tool.strict_args,
                    description: None,
                    enum_values: vec![],
                    default: arg.default.clone(),
                };
                // Non-required without default: use type-appropriate fallback
                if !tp.required && tp.default.is_none() {
                    tp.default = Some(from_ir_arg_type(&arg.arg_type).rust_default().to_string());
                }
                tp
            })
            .collect();

        let extract_input = ArgExtractInput {
            args_var: "args".into(),
            params,
        };
        let extract_code = gen_arg_extract(&extract_input);

        // Indent the extraction code by 4 levels
        for line in extract_code.lines() {
            if !line.is_empty() {
                w(out, 4, line.trim());
            }
        }

        // Dispatch to trait method
        let method_name = swap_prefix(&tool.name, "jarvis_", "execute_");
        let arg_names: Vec<&str> = tool.args.iter().map(|a| a.name.as_str()).collect();
        w(
            out,
            4,
            &format!("self.{}({}).await", method_name, arg_names.join(", ")),
        );

        w(out, 3, "}");
    }

    w(
        out,
        3,
        "_ => anyhow::bail!(\"unknown tool: {name}\"),",
    );
    w(out, 2, "}");
    w(out, 1, "}");
}

// ---------------------------------------------------------------------------
// Trait (Generation Gap)
// ---------------------------------------------------------------------------

fn gen_trait(out: &mut String, decl: &McpModuleDecl) {
    let trait_name = format!("{}Logic", decl.struct_name);

    w(
        out,
        0,
        "// ═══════════════════════════════════════════════════════════",
    );
    w(
        out,
        0,
        "// \u{1f916} GENERATED CONTRACT — implement in custom.rs",
    );
    w(
        out,
        0,
        "// ═══════════════════════════════════════════════════════════\n",
    );

    w(out, 0, "#[allow(async_fn_in_trait)]");
    w(out, 0, &format!("pub trait {trait_name} {{"));

    for tool in &decl.tools {
        let method_name = swap_prefix(&tool.name, "jarvis_", "execute_");
        let mut params = vec!["&self".to_string()];
        for arg in &tool.args {
            let rust_type = from_ir_arg_type(&arg.arg_type).rust_ref_type();
            params.push(format!("{}: {}", arg.name, rust_type));
        }
        w(
            out,
            1,
            &format!(
                "async fn {}({}) -> Result<Value>;",
                method_name,
                params.join(", ")
            ),
        );
    }

    w(out, 0, "}\n");
}

