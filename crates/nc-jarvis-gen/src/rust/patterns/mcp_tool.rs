#[cfg(test)]
mod tests {
    use super::*;
    use nc_parser::SexpNode;

    fn parse_and_gen(input: &str) -> String {
        let sexp = SexpNode::parse_one(input).unwrap();
        let decl = McpModuleDecl::from_sexp(&sexp).unwrap();
        generate_mcp_module(&decl)
    }

    #[test]
    fn generates_tool_schema() {
        let output = parse_and_gen(
            r#"(mcp-module board
          :struct BoardModule
          :deps ((storage "Arc<Storage>"))
          (tool jarvis_board_delete
            :description "Delete a task"
            (input (id string :required))
            :returns "Value"))"#,
        );

        assert!(output.contains("GENERATED BY FORGE"));
        assert!(output.contains("pub struct BoardModule"));
        assert!(output.contains("fn tools(&self) -> Vec<ToolSchema>"));
        assert!(output.contains("\"jarvis_board_delete\""));
        assert!(output.contains("\"required\": [\"id\"]"));
        assert!(output.contains("async fn handle_tool"));
        assert!(output.contains("pub trait BoardModuleLogic"));
        assert!(output.contains("async fn execute_board_delete"));
    }

    #[test]
    fn generates_json_schema_enum() {
        let output = parse_and_gen(
            r#"(mcp-module test
          :struct TestModule
          :deps ((storage "Arc<Storage>"))
          (tool jarvis_test_foo
            :description "Test"
            (input (priority string :enum (high medium low) :default "medium"))
            :returns "Value"))"#,
        );

        assert!(output.contains("\"enum\": [\"high\", \"medium\", \"low\"]"));
        assert!(output.contains("unwrap_or(\"medium\")"));
    }

    #[test]
    fn full_pattern_file() {
        let manifest = std::env::var("CARGO_MANIFEST_DIR").unwrap();
        let path = std::path::Path::new(&manifest)
            .parent()
            .unwrap()
            .parent()
            .unwrap()
            .join("patterns/jarvis-mcp-tools.lisp");
        let src = std::fs::read_to_string(&path).unwrap();
        let nodes = SexpNode::parse(&src).unwrap();
        let modules = nc_jarvis_ir::mcp_tool::parse_mcp_modules(&nodes).unwrap();

        for m in &modules {
            let output = generate_mcp_module(m);
            let open = output.matches('{').count();
            let close = output.matches('}').count();
            assert_eq!(open, close, "{}: unbalanced braces", m.name);
            eprintln!(
                "  {} -> {} lines, {} tools",
                m.name,
                output.lines().count(),
                m.tools.len()
            );
        }
    }
}
