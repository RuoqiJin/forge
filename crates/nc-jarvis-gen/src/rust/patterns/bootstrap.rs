//! Bootstrap code generator.
//!
//! Generates `BootstrapContext` struct + `impl BootstrapContext { pub async fn init() }`.
//! Topologically-sorted infra init + module registration + worker spawn.
//! Replaces ~400 lines of hand-wired Arc::new/clone in main.rs.
//!
//! ## Layer 2 Principle
//!
//! This file delegates struct/impl generation to Layer 1 atoms.
//! Only header/imports remain as direct w() calls.

use nc_jarvis_ir::bootstrap::*;

use crate::rust::atoms::impl_block::{gen_impl_block, ImplBlockInput, MethodDef};
use crate::rust::atoms::struct_def::{gen_struct_def, FieldDef, StructDefInput, Visibility};
use crate::quarks::derive_attr::DeriveSet;

pub fn generate_bootstrap(decl: &BootstrapDecl) -> String {
    let mut out = String::with_capacity(8192);

    // ── Header (direct w() calls) ──
    w(&mut out, 0, "// \u{1f916} GENERATED BY FORGE - DO NOT EDIT");
    w(&mut out, 0, &format!("// Source: patterns/jarvis-bootstrap.lisp (bootstrap {})", decl.name));
    w(&mut out, 0, &format!("// Infra: {} components | Modules: {} | Workers: {}",
        decl.infra.len(), decl.modules.len(), decl.workers.len()));
    out.push('\n');

    // Topological sort (infra components are already in dependency order in the Lisp)
    // Validate: no cycles
    if let Err(cycle) = validate_no_cycles(&decl.infra) {
        w(&mut out, 0, &format!("// ERROR: circular dependency detected: {cycle}"));
        w(&mut out, 0, "compile_error!(\"Circular dependency in bootstrap Lisp\");");
        return out;
    }

    // ── BootstrapContext struct (delegate to struct_def atom) ──
    out.push_str(&gen_context_struct(decl));
    out.push('\n');

    // ── impl BootstrapContext { pub async fn init() } (delegate to impl_block atom) ──
    out.push_str(&gen_context_impl(decl));
    out.push('\n');

    out
}

// ---------------------------------------------------------------------------
// BootstrapContext struct — delegated to struct_def atom
// ---------------------------------------------------------------------------

fn gen_context_struct(decl: &BootstrapDecl) -> String {
    let mut fields: Vec<FieldDef> = decl.infra.iter().map(|comp| {
        let full_type = if let Some(ref wrap) = comp.wrap {
            format!("{}<{}>", wrap, comp.rust_type)
        } else {
            comp.rust_type.clone()
        };
        FieldDef {
            name: comp.name.clone(),
            rust_type: full_type,
            visibility: Visibility::Pub,
            doc: None,
            serde_rename: None,
            serde_default: false,
            serde_skip_serializing_if: None,
            serde_default_fn: None,
            extra_field_attrs: vec![],
        }
    }).collect();

    // module_host field
    fields.push(FieldDef {
        name: "module_host".into(),
        rust_type: "Arc<ModuleHost>".into(),
        visibility: Visibility::Pub,
        doc: None,
        serde_rename: None,
        serde_default: false,
        serde_skip_serializing_if: None,
        serde_default_fn: None,
        extra_field_attrs: vec![],
    });

    let input = StructDefInput {
        name: "BootstrapContext".into(),
        fields,
        derives: DeriveSet {
            debug: false,
            clone: false,
            serialize: false,
            deserialize: false,
            partial_eq: false,
            custom: vec![],
        },
        doc: Some("All initialized components, available after bootstrap.".into()),
        serde_rename_all: None,
        extra_struct_attrs: vec![],
        default_impl: false,
    };

    gen_struct_def(&input)
}

// ---------------------------------------------------------------------------
// impl BootstrapContext — delegated to impl_block atom
// ---------------------------------------------------------------------------

fn gen_context_impl(decl: &BootstrapDecl) -> String {
    let body = build_init_body(decl);

    let input = ImplBlockInput {
        type_name: "BootstrapContext".into(),
        trait_name: None,
        methods: vec![MethodDef {
            signature: "pub async fn init(config: &Config) -> Result<Self>".into(),
            body,
            doc: Some("Initialize all components in topological order, register MCP modules, and spawn workers.".into()),
            attributes: vec![],
        }],
    };

    gen_impl_block(&input)
}

/// Build the body of `init()` as a pre-formatted String.
/// Each line is at indent level 0 relative to the method body;
/// the impl_block atom will indent them by 2 levels.
fn build_init_body(decl: &BootstrapDecl) -> String {
    let mut body = String::with_capacity(4096);

    // ── Phase 1: Infrastructure init (topologically sorted) ──
    body.push_str("// ═══ Phase 1: Infrastructure (topological order) ═══\n");

    for comp in &decl.infra {
        let default_init = format!(
            "{}::new({})",
            comp.rust_type,
            comp.deps.iter().map(|d| format!("{d}.clone()")).collect::<Vec<_>>().join(", ")
        );
        let init = comp.init_expr.as_deref().unwrap_or(&default_init);

        if let Some(ref wrap) = comp.wrap {
            body.push_str(&format!("let {} = {}({});\n", comp.name, wrap, init));
        } else {
            body.push_str(&format!("let {} = {};\n", comp.name, init));
        }

        if let Some(ref post) = comp.post_init {
            body.push_str(&format!("{};\n", post));
        }

        body.push_str(&format!("tracing::debug!(\"init: {}\");\n", comp.name));
        body.push('\n');
    }

    // ── Phase 2: ModuleHost registration ──
    body.push_str("// ═══ Phase 2: MCP Module Registration ═══\n");
    body.push_str("let mut module_host = ModuleHost::new();\n");

    for module in &decl.modules {
        let args = if let Some(ref raw) = module.deps_raw {
            raw.clone()
        } else {
            module.deps.iter().map(|d| format!("{d}.clone()")).collect::<Vec<_>>().join(", ")
        };
        body.push_str(&format!(
            "module_host.register(Arc::new({}::new({})));\n",
            module.struct_name, args
        ));
    }

    body.push_str("let module_host = Arc::new(module_host);\n");
    body.push_str("module_host.init_all(&module_ctx).await?;\n");
    body.push('\n');

    // ── Phase 3: Worker spawn ──
    body.push_str("// ═══ Phase 3: Worker Spawn ═══\n");

    for worker in &decl.workers {
        let init = worker.init_expr.as_deref().unwrap_or("todo!(\"worker init\")");

        if worker.method == "start" {
            // Static method pattern (MessagePersister::start)
            body.push_str(&format!("{};\n", init));
        } else {
            // Instance method pattern (worker.run())
            body.push_str("{\n");
            body.push_str(&format!("    let worker = {};\n", init));
            body.push_str("    tokio::spawn(async move {\n");
            body.push_str(&format!(
                "        if let Err(e) = worker.{}().await {{ tracing::error!(error = %e, \"{} crashed\"); }}\n",
                worker.method, worker.name
            ));
            body.push_str("    });\n");
            body.push_str("}\n");
        }
        body.push_str(&format!("tracing::info!(\"{} started\");\n", worker.name));
        body.push('\n');
    }

    // ── Return context ──
    body.push_str("Ok(Self {\n");
    for comp in &decl.infra {
        body.push_str(&format!("    {},\n", comp.name));
    }
    body.push_str("    module_host,\n");
    body.push_str("})");

    body
}

/// Validate no circular dependencies using simple DFS.
fn validate_no_cycles(components: &[ComponentDecl]) -> Result<(), String> {
    use std::collections::{HashMap, HashSet};

    let name_to_idx: HashMap<&str, usize> = components.iter()
        .enumerate()
        .map(|(i, c)| (c.name.as_str(), i))
        .collect();

    let mut visited = HashSet::new();
    let mut stack = HashSet::new();

    fn dfs(
        idx: usize,
        components: &[ComponentDecl],
        name_to_idx: &HashMap<&str, usize>,
        visited: &mut HashSet<usize>,
        stack: &mut HashSet<usize>,
    ) -> Result<(), String> {
        if stack.contains(&idx) {
            return Err(format!("cycle involving: {}", components[idx].name));
        }
        if visited.contains(&idx) {
            return Ok(());
        }
        stack.insert(idx);
        for dep in &components[idx].deps {
            if let Some(&dep_idx) = name_to_idx.get(dep.as_str()) {
                dfs(dep_idx, components, name_to_idx, visited, stack)?;
            }
        }
        stack.remove(&idx);
        visited.insert(idx);
        Ok(())
    }

    for i in 0..components.len() {
        dfs(i, components, &name_to_idx, &mut visited, &mut stack)?;
    }
    Ok(())
}

fn w(out: &mut String, indent: usize, line: &str) {
    for _ in 0..indent { out.push_str("    "); }
    out.push_str(line);
    out.push('\n');
}

#[cfg(test)]
mod tests {
    use super::*;
    use nc_parser::SexpNode;

    #[test]
    fn full_pattern_bootstrap() {
        let manifest = std::env::var("CARGO_MANIFEST_DIR").unwrap();
        let path = std::path::Path::new(&manifest)
            .parent().unwrap().parent().unwrap()
            .join("patterns/jarvis-bootstrap.lisp");
        let src = std::fs::read_to_string(&path).unwrap();
        let node = SexpNode::parse_one(&src).unwrap();
        let decl = BootstrapDecl::from_sexp(&node).unwrap();
        let output = generate_bootstrap(&decl);

        assert!(output.contains("GENERATED BY FORGE"));
        assert!(output.contains("pub struct BootstrapContext"));
        assert!(output.contains("impl BootstrapContext {"));
        assert!(output.contains("pub async fn init(config: &Config) -> Result<Self>"));
        assert!(output.contains("Phase 1: Infrastructure"));
        assert!(output.contains("Phase 2: MCP Module Registration"));
        assert!(output.contains("Phase 3: Worker Spawn"));

        // Verify topological order: storage after pool
        let pool_pos = output.find("let pool").unwrap();
        let storage_pos = output.find("let storage").unwrap();
        assert!(pool_pos < storage_pos, "pool must init before storage");

        // Verify cycle detection works
        assert!(!output.contains("compile_error!"));

        // Brace balance
        let open = output.matches('{').count();
        let close = output.matches('}').count();
        assert_eq!(open, close, "unbalanced: {open} vs {close}");

        eprintln!("=== Bootstrap generated: {} lines ===", output.lines().count());
    }

    #[test]
    fn detect_cycle() {
        let comps = vec![
            ComponentDecl {
                name: "a".into(), rust_type: "A".into(), wrap: None,
                deps: vec!["b".into()], init_expr: None, post_init: None,
            },
            ComponentDecl {
                name: "b".into(), rust_type: "B".into(), wrap: None,
                deps: vec!["a".into()], init_expr: None, post_init: None,
            },
        ];
        assert!(validate_no_cycles(&comps).is_err());
    }
}
