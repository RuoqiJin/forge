//! S3 Dispatcher code generator.
//!
//! Generates the "S3 trait delegation layer":
//! - `impl S3 for FS` block with delegate methods and custom trampolines
//! - `custom.rs` scaffold with `FsCustomLogic` trait and `todo!()` bodies
//!
//! Two entry points:
//! - `generate_s3_dispatcher` → **generated.rs** (regenerated on every forge run)
//! - `generate_s3_dispatcher_custom` → **custom.rs** (write-once scaffold)

use nc_jarvis_ir::s3_dispatcher::*;

use crate::rust::atoms::impl_block::{gen_impl_block as gen_impl_block_atom, ImplBlockInput, MethodDef};
use crate::rust::atoms::trait_contract::{gen_trait_contract, TraitContractInput, TraitMethodDef};
use crate::rust::atoms::w;

// ---------------------------------------------------------------------------
// Public entry points
// ---------------------------------------------------------------------------

/// Generate **generated.rs** — the `impl S3 for FS` block.
pub fn generate_s3_dispatcher(decl: &S3DispatcherDecl) -> String {
    let mut out = String::with_capacity(8192);

    gen_header(&mut out, decl);
    gen_imports(&mut out, decl);
    out.push('\n');
    gen_impl_block(&mut out, decl);

    out
}

/// Generate **custom.rs** — write-once scaffold with `FsCustomLogic` trait.
pub fn generate_s3_dispatcher_custom(decl: &S3DispatcherDecl) -> String {
    let mut out = String::with_capacity(4096);

    gen_custom_header(&mut out);
    gen_custom_imports(&mut out);
    out.push('\n');
    gen_custom_trait(&mut out, decl);
    out.push('\n');
    gen_custom_impl(&mut out, decl);

    out
}

// ---------------------------------------------------------------------------
// Header + imports (generated.rs)
// ---------------------------------------------------------------------------

fn gen_header(out: &mut String, decl: &S3DispatcherDecl) {
    w(out, 0, "// \u{1f916} GENERATED BY FORGE - DO NOT EDIT");
    w(
        out,
        0,
        &format!(
            "// Source: .missiond/intent-s3-dispatcher.lisp (s3-dispatcher {})",
            decl.name
        ),
    );
    w(out, 0, "// Pattern: s3-dispatcher (S3 trait delegation layer)");
    w(
        out,
        0,
        &format!(
            "// Delegates: {} | Custom trampolines: {}",
            decl.delegates.len(),
            decl.customs.len()
        ),
    );
    w(out, 0, "");
}

fn gen_imports(out: &mut String, decl: &S3DispatcherDecl) {
    for imp in &decl.imports {
        w(out, 0, &format!("use {};", imp));
    }
}

// ---------------------------------------------------------------------------
// impl S3 for FS
// ---------------------------------------------------------------------------

fn gen_impl_block(out: &mut String, decl: &S3DispatcherDecl) {
    // Optional #[async_trait] attribute — emitted before the atom-generated block
    if let Some(ref attr) = decl.async_trait {
        w(out, 0, &format!("#[{}]", attr));
    }

    // Build all methods: delegates first, then custom trampolines
    let mut methods: Vec<MethodDef> = Vec::new();

    for delegate in &decl.delegates {
        methods.push(build_delegate_method(delegate));
    }
    for custom in &decl.customs {
        methods.push(build_custom_trampoline(custom));
    }

    let impl_code = gen_impl_block_atom(&ImplBlockInput {
        type_name: decl.struct_name.clone(),
        trait_name: Some("S3".into()),
        methods,
    });
    out.push_str(&impl_code);
    w(out, 0, "");
}

fn build_delegate_method(delegate: &S3DelegateDecl) -> MethodDef {
    // Build #[instrument(...)] attribute if present
    let attributes = match &delegate.instrument {
        Some(inst) => vec![build_instrument_attr_str(inst)],
        None => vec![],
    };

    // Build method body
    let mut body_lines: Vec<String> = Vec::new();

    // record_s3_op if present
    if let Some(ref op) = delegate.record_s3_op {
        if delegate.record_s3_op_bucket.as_deref() == Some("*") {
            body_lines.push(format!("record_s3_op(S3Operation::{}, \"*\");", op));
        } else {
            body_lines.push(format!(
                "record_s3_op(S3Operation::{}, &req.input.bucket);",
                op
            ));
        }
    }

    // Usecase instantiation
    let usecase_name = usecase_kind_to_name(&delegate.usecase);
    body_lines.push(format!(
        "let usecase = Default{}Usecase::from_global();",
        usecase_name
    ));

    // Usecase execution
    if delegate.pass_self {
        body_lines.push(format!(
            "usecase.execute_{}(self, req).await",
            delegate.method
        ));
    } else {
        body_lines.push(format!(
            "usecase.execute_{}(req).await",
            delegate.method
        ));
    }

    MethodDef {
        signature: format!(
            "async fn {}(&self, req: S3Request<{}>) -> S3Result<S3Response<{}>>",
            delegate.method, delegate.input_type, delegate.output_type
        ),
        body: body_lines.join("\n"),
        doc: None,
        attributes,
    }
}

fn build_instrument_attr_str(inst: &InstrumentDecl) -> String {
    let skip_list = inst.skip.join(", ");

    if inst.fields.is_empty() {
        format!(
            "#[instrument(level = \"{}\", skip({}))]",
            inst.level, skip_list
        )
    } else {
        let fields_str: Vec<String> = inst
            .fields
            .iter()
            .map(|(name, expr)| format!("{} = {}", name, expr))
            .collect();
        format!(
            "#[instrument(level = \"{}\", skip({}), fields({}))]",
            inst.level,
            skip_list,
            fields_str.join(", ")
        )
    }
}

fn build_custom_trampoline(custom: &S3CustomDecl) -> MethodDef {
    MethodDef {
        signature: format!(
            "async fn {}(&self, req: S3Request<{}>) -> S3Result<S3Response<{}>>",
            custom.method, custom.input_type, custom.output_type
        ),
        body: format!("self.custom_{}(req).await", custom.method),
        doc: None,
        attributes: vec![],
    }
}

// ---------------------------------------------------------------------------
// custom.rs generation
// ---------------------------------------------------------------------------

fn gen_custom_header(out: &mut String) {
    w(out, 0, "// XjpFS custom S3 handlers \u{2014} hand-maintained");
    w(
        out,
        0,
        "// These methods contain business logic that cannot be generated.",
    );
    w(
        out,
        0,
        "// Implement FsCustomLogic for FS to provide the actual implementations.",
    );
    w(out, 0, "");
}

fn gen_custom_imports(out: &mut String) {
    w(
        out,
        0,
        "use s3s::{S3Error, S3ErrorCode, S3Request, S3Response, S3Result, dto::*, s3_error};",
    );
    w(out, 0, "use super::FS;");
}

fn gen_custom_trait(out: &mut String, decl: &S3DispatcherDecl) {
    w(out, 0, "#[allow(async_fn_in_trait)]");

    let methods: Vec<TraitMethodDef> = decl
        .customs
        .iter()
        .map(|c| TraitMethodDef {
            name: format!("custom_{}", c.method),
            params: vec![
                ("req".into(), format!("S3Request<{}>", c.input_type)),
            ],
            return_type: format!("S3Result<S3Response<{}>>", c.output_type),
            is_async: true,
            doc: None,
            has_default: false,
            has_self: true,
        })
        .collect();

    let trait_code = gen_trait_contract(&TraitContractInput {
        name: "FsCustomLogic".into(),
        doc: None,
        methods,
        is_async_trait: false,
    });
    out.push_str(&trait_code);
}

fn gen_custom_impl(out: &mut String, decl: &S3DispatcherDecl) {
    let methods: Vec<MethodDef> = decl
        .customs
        .iter()
        .map(|c| MethodDef {
            signature: format!(
                "async fn custom_{}(&self, req: S3Request<{}>) -> S3Result<S3Response<{}>>",
                c.method, c.input_type, c.output_type
            ),
            body: "todo!(\"migrate from original ecfs.rs\")".into(),
            doc: None,
            attributes: vec![],
        })
        .collect();

    let impl_code = gen_impl_block_atom(&ImplBlockInput {
        type_name: "FS".into(),
        trait_name: Some("FsCustomLogic".into()),
        methods,
    });
    out.push_str(&impl_code);
    out.push('\n');
}

// ---------------------------------------------------------------------------
// Utilities
// ---------------------------------------------------------------------------

fn usecase_kind_to_name(kind: &UsecaseKind) -> &'static str {
    match kind {
        UsecaseKind::Bucket => "Bucket",
        UsecaseKind::Object => "Object",
        UsecaseKind::Multipart => "Multipart",
    }
}

