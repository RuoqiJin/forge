#[cfg(test)]
mod tests {
    use super::*;
    use nc_jarvis_ir::s3_dispatcher::*;

    fn make_minimal_decl() -> S3DispatcherDecl {
        S3DispatcherDecl {
            name: "fs".into(),
            struct_name: "FS".into(),
            async_trait: Some("async_trait::async_trait".into()),
            imports: vec!["s3s::{S3, S3Request, S3Response, S3Result, dto::*}".into()],
            delegates: vec![S3DelegateDecl {
                method: "head_bucket".into(),
                input_type: "HeadBucketInput".into(),
                output_type: "HeadBucketOutput".into(),
                usecase: UsecaseKind::Bucket,
                instrument: Some(InstrumentDecl {
                    level: "debug".into(),
                    skip: vec!["self".into(), "req".into()],
                    fields: vec![],
                }),
                record_s3_op: None,
                record_s3_op_bucket: None,
                pass_self: false,
            }],
            customs: vec![S3CustomDecl {
                method: "get_bucket_website".into(),
                input_type: "GetBucketWebsiteInput".into(),
                output_type: "GetBucketWebsiteOutput".into(),
            }],
        }
    }

    #[test]
    fn generated_has_balanced_braces() {
        let decl = make_minimal_decl();
        let code = generate_s3_dispatcher(&decl);
        let opens = code.chars().filter(|c| *c == '{').count();
        let closes = code.chars().filter(|c| *c == '}').count();
        assert_eq!(opens, closes, "unbalanced braces:\n{}", code);
    }

    #[test]
    fn delegate_with_instrument_and_record() {
        // Test a delegate with both instrument and record_s3_op
        let mut decl = make_minimal_decl();
        decl.delegates[0].record_s3_op = Some("HeadBucket".into());
        let code = generate_s3_dispatcher(&decl);
        assert!(code.contains("#[instrument(level = \"debug\", skip(self, req))]"));
        assert!(code.contains("record_s3_op(S3Operation::HeadBucket, &req.input.bucket)"));
    }

    #[test]
    fn custom_generates_trampoline_and_trait() {
        let decl = make_minimal_decl();
        let code = generate_s3_dispatcher(&decl);
        let custom_code = generate_s3_dispatcher_custom(&decl);
        assert!(code.contains("self.custom_get_bucket_website(req).await"));
        assert!(custom_code.contains("pub trait FsCustomLogic"));
        assert!(custom_code.contains("async fn custom_get_bucket_website"));
    }

    #[test]
    fn instrument_with_fields() {
        let mut decl = make_minimal_decl();
        decl.delegates[0].instrument = Some(InstrumentDecl {
            level: "debug".into(),
            skip: vec!["self".into(), "req".into()],
            fields: vec![("start_time".into(), "?time::OffsetDateTime::now_utc()".into())],
        });
        let code = generate_s3_dispatcher(&decl);
        assert!(code.contains("fields(start_time = ?time::OffsetDateTime::now_utc())"));
    }

    #[test]
    fn record_s3_op_with_wildcard_bucket() {
        let mut decl = make_minimal_decl();
        decl.delegates[0].method = "list_buckets".into();
        decl.delegates[0].input_type = "ListBucketsInput".into();
        decl.delegates[0].output_type = "ListBucketsOutput".into();
        decl.delegates[0].record_s3_op = Some("ListBuckets".into());
        decl.delegates[0].record_s3_op_bucket = Some("*".into());
        let code = generate_s3_dispatcher(&decl);
        assert!(code.contains("record_s3_op(S3Operation::ListBuckets, \"*\")"));
        assert!(!code.contains("&req.input.bucket"));
    }

    #[test]
    fn pass_self_delegate() {
        let mut decl = make_minimal_decl();
        decl.delegates[0].method = "put_object".into();
        decl.delegates[0].input_type = "PutObjectInput".into();
        decl.delegates[0].output_type = "PutObjectOutput".into();
        decl.delegates[0].usecase = UsecaseKind::Object;
        decl.delegates[0].pass_self = true;
        let code = generate_s3_dispatcher(&decl);
        assert!(code.contains("usecase.execute_put_object(self, req).await"));
        assert!(code.contains("DefaultObjectUsecase::from_global()"));
    }

    #[test]
    fn custom_rs_has_todo_bodies() {
        let decl = make_minimal_decl();
        let code = generate_s3_dispatcher_custom(&decl);
        assert!(code.contains("todo!(\"migrate from original ecfs.rs\")"));
        assert!(code.contains("impl FsCustomLogic for FS"));
    }

    #[test]
    fn header_contains_counts() {
        let decl = make_minimal_decl();
        let code = generate_s3_dispatcher(&decl);
        assert!(code.contains("// Delegates: 1 | Custom trampolines: 1"));
    }

    #[test]
    fn custom_rs_has_balanced_braces() {
        let decl = make_minimal_decl();
        let code = generate_s3_dispatcher_custom(&decl);
        let opens = code.chars().filter(|c| *c == '{').count();
        let closes = code.chars().filter(|c| *c == '}').count();
        assert_eq!(opens, closes, "unbalanced braces in custom.rs:\n{}", code);
    }

    #[test]
    fn multipart_usecase_mapping() {
        let mut decl = make_minimal_decl();
        decl.delegates[0].method = "abort_multipart_upload".into();
        decl.delegates[0].input_type = "AbortMultipartUploadInput".into();
        decl.delegates[0].output_type = "AbortMultipartUploadOutput".into();
        decl.delegates[0].usecase = UsecaseKind::Multipart;
        let code = generate_s3_dispatcher(&decl);
        assert!(code.contains("DefaultMultipartUsecase::from_global()"));
    }

    /// Full integration test: read real Lisp → IR → codegen → write to .forge-output/
    #[test]
    #[ignore] // requires local xiaojinpro-gateway checkout
    fn full_stamp_from_real_lisp() {
        let lisp_path = "fixtures/xjpfs/.missiond/intent-s3-dispatcher.lisp";
        let lisp_src = std::fs::read_to_string(lisp_path)
            .expect("Failed to read intent-s3-dispatcher.lisp");
        let node = nc_parser::SexpNode::parse_one(&lisp_src).expect("Failed to parse S-EXP");
        let decl = nc_jarvis_ir::s3_dispatcher::S3DispatcherDecl::from_sexp(&node)
            .expect("Failed to lower to IR");

        // Verify IR counts
        assert_eq!(decl.delegates.len(), 65, "expected 65 delegates, got {}", decl.delegates.len());
        assert_eq!(decl.customs.len(), 10, "expected 10 customs, got {}", decl.customs.len());
        assert_eq!(decl.struct_name, "FS");

        // Generate
        let generated = generate_s3_dispatcher(&decl);
        let custom = generate_s3_dispatcher_custom(&decl);

        // Balanced braces
        let g_open = generated.chars().filter(|c| *c == '{').count();
        let g_close = generated.chars().filter(|c| *c == '}').count();
        assert_eq!(g_open, g_close, "generated.rs unbalanced braces");

        let c_open = custom.chars().filter(|c| *c == '{').count();
        let c_close = custom.chars().filter(|c| *c == '}').count();
        assert_eq!(c_open, c_close, "custom.rs unbalanced braces");

        // Key assertions on generated code
        assert!(generated.contains("impl S3 for FS"));
        assert!(generated.contains("#[async_trait::async_trait]"));
        assert!(generated.contains("DefaultBucketUsecase::from_global()"));
        assert!(generated.contains("DefaultObjectUsecase::from_global()"));
        assert!(generated.contains("DefaultMultipartUsecase::from_global()"));
        assert!(generated.contains("self.custom_delete_bucket_website(req).await"));
        assert!(generated.contains("usecase.execute_put_object(self, req).await")); // pass_self
        assert!(generated.contains("record_s3_op(S3Operation::ListBuckets, \"*\")")); // wildcard

        // Write to .forge-output/
        let output_dir = "fixtures/xjpfs/.forge-output";
        std::fs::create_dir_all(output_dir).expect("create .forge-output");
        std::fs::write(format!("{}/generated.rs", output_dir), &generated).expect("write generated.rs");
        std::fs::write(format!("{}/custom.rs", output_dir), &custom).expect("write custom.rs");

        eprintln!("=== STAMP COMPLETE ===");
        eprintln!("generated.rs: {} lines", generated.lines().count());
        eprintln!("custom.rs: {} lines", custom.lines().count());
        eprintln!("Output: {}", output_dir);
    }
}
