#[cfg(test)]
mod tests {
    use super::*;
    use nc_parser::SexpNode;

    #[test]
    fn generates_enum_and_transitions() {
        let sexp = SexpNode::parse_one(r#"(state-machine test
          :enum TestState
          :derive (Debug Clone Copy PartialEq Eq)
          (states (A :doc "first") (B) (C))
          (transitions
            (A -> B :trigger "go")
            (B -> C)
            (B -> A :debounce 300ms))
          (group active (A B) :method is_active)
          (guards (send :requires A :error "must be A")))"#).unwrap();
        let decl = StateMachineDecl::from_sexp(&sexp).unwrap();
        let output = generate_state_machine(&decl);

        assert!(output.contains("GENERATED BY FORGE"));
        assert!(output.contains("pub enum TestState"));
        assert!(output.contains("/// first"));
        assert!(output.contains("A,"));
        assert!(output.contains("B,"));
        assert!(output.contains("C,"));
        assert!(output.contains("fn is_active(&self) -> bool"));
        assert!(output.contains("fn try_transition(from: Self, to: Self)"));
        assert!(output.contains("(Self::A, Self::B) => Ok(())"));
        assert!(output.contains("(Self::B, Self::A) => Ok(()),"));
        assert!(output.contains("debounce: 300ms"));
        assert!(output.contains("fn ensure_send(&self)"));
        assert!(output.contains("TestStateTransitionError"));
        assert!(output.contains("fn debounce_ms(from: Self, to: Self)"));
        assert!(output.contains("fn valid_transitions(&self)"));

        let open = output.matches('{').count();
        let close = output.matches('}').count();
        assert_eq!(open, close, "unbalanced: {open} vs {close}");
    }

    #[test]
    fn full_pattern_file() {
        let manifest = std::env::var("CARGO_MANIFEST_DIR").unwrap();
        let path = std::path::Path::new(&manifest)
            .parent().unwrap().parent().unwrap()
            .join("patterns/jarvis-state-machine.lisp");
        let src = std::fs::read_to_string(&path).unwrap();
        let node = SexpNode::parse_one(&src).unwrap();
        let decl = StateMachineDecl::from_sexp(&node).unwrap();
        let output = generate_state_machine(&decl);

        assert!(output.contains("pub enum SessionState"));
        assert!(output.contains("Starting,"));
        assert!(output.contains("Exited,"));
        assert!(output.contains("fn is_processing(&self)"));
        assert!(output.contains("fn try_transition("));
        assert!(output.contains("fn ensure_send("));
        assert!(output.contains("fn ensure_kill("));
        assert!(output.contains("pub trait SessionStateDetector"));
        assert!(output.contains("fn detect_from_screen("));
        assert!(output.contains("fn has_activity_timer("));
        assert!(output.contains("SessionStateTransitionError"));

        let open = output.matches('{').count();
        let close = output.matches('}').count();
        assert_eq!(open, close, "unbalanced: {open} vs {close}");

        eprintln!("=== SessionState generated: {} lines ===", output.lines().count());
    }
}
