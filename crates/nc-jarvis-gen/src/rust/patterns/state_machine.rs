//! State Machine code generator.
//!
//! Generates:
//! - State enum with derives
//! - Group helper methods (e.g. is_processing())
//! - Transition validator: try_transition() with whitelist
//! - Guard methods (e.g. ensure_idle())
//! - Trait contract for screen detection (Generation Gap)

use nc_jarvis_ir::state_machine::*;

use crate::rust::atoms::enum_def::{gen_enum_def, EnumDefInput, VariantDef};
use crate::rust::atoms::impl_block::{gen_impl_block, ImplBlockInput, MethodDef};
use crate::rust::atoms::match_arm::{gen_match_expr, MatchArmDef, MatchExprInput};
use crate::rust::atoms::struct_def::{gen_struct_def, DeriveSet, FieldDef, StructDefInput, Visibility};
use crate::rust::atoms::trait_contract::{gen_trait_contract, TraitContractInput, TraitMethodDef};

pub fn generate_state_machine(decl: &StateMachineDecl) -> String {
    let mut out = String::with_capacity(4096);

    gen_header(&mut out, decl);
    gen_imports(&mut out);
    out.push('\n');

    // State enum via enum_def atom
    out.push_str(&build_state_enum(decl));

    // Display impl via impl_block atom
    out.push_str(&build_display_impl(decl));
    out.push('\n');

    // Main impl block (groups, transitions, guards, valid_transitions) via impl_block atom
    out.push_str(&build_main_impl(decl));
    out.push('\n');

    // Transition error struct via struct_def + impl_block atoms
    out.push_str(&build_transition_error(decl));

    // Trait contract via trait_contract atom
    if let Some(ref tr) = decl.trait_decl {
        out.push_str(&build_trait(tr));
        out.push('\n');
    }

    out
}

// ---------------------------------------------------------------------------
// Header + imports (kept as direct w() calls)
// ---------------------------------------------------------------------------

fn gen_header(out: &mut String, decl: &StateMachineDecl) {
    w(out, 0, "// \u{1f916} GENERATED BY FORGE - DO NOT EDIT");
    w(out, 0, &format!("// Source: patterns/jarvis-state-machine.lisp (state-machine {})", decl.name));
    w(out, 0, &format!("// States: {} | Transitions: {}", decl.states.len(), decl.transitions.len()));
    out.push('\n');
}

fn gen_imports(out: &mut String) {
    w(out, 0, "use serde::{Serialize, Deserialize};");
    w(out, 0, "use std::fmt;");
}

// ---------------------------------------------------------------------------
// State enum — via enum_def atom
// ---------------------------------------------------------------------------

fn build_state_enum(decl: &StateMachineDecl) -> String {
    // Build DeriveSet from the IR's derive list
    let mut derives = DeriveSet {
        debug: false,
        clone: false,
        serialize: true,
        deserialize: true,
        partial_eq: false,
        custom: vec![],
    };
    for d in &decl.derives {
        match d.as_str() {
            "Debug" => derives.debug = true,
            "Clone" => derives.clone = true,
            "Serialize" => derives.serialize = true,
            "Deserialize" => derives.deserialize = true,
            "PartialEq" => derives.partial_eq = true,
            other => derives.custom.push(other.to_string()),
        }
    }

    let input = EnumDefInput {
        name: decl.enum_name.clone(),
        variants: decl.states.iter().map(|s| VariantDef {
            name: s.name.clone(),
            doc: s.doc.clone(),
            // Use PascalCase name as str_value to avoid snake_case conversion in Display
            str_value: Some(s.name.clone()),
        }).collect(),
        derives,
        derive_display: false,  // We generate Display separately with fmt:: prefix
        derive_from_str: false,
        doc: None,
        serde_rename_all: None,
        extra_enum_attrs: vec![],
        gen_as_str_method: false,
        gen_from_str_method: false,
        from_str_default: None,
    };
    gen_enum_def(&input)
}

// ---------------------------------------------------------------------------
// Display impl — via impl_block + match_arm atoms
// ---------------------------------------------------------------------------

fn build_display_impl(decl: &StateMachineDecl) -> String {
    let match_input = MatchExprInput {
        subject: "self".into(),
        arms: decl.states.iter().map(|s| MatchArmDef {
            pattern: format!("Self::{}", s.name),
            body: format!("write!(f, \"{}\")", s.name),
            doc: None,
        }).collect(),
        fallback: None,
        indent: 0,
    };

    let match_code = gen_match_expr(&match_input);

    let impl_input = ImplBlockInput {
        type_name: decl.enum_name.clone(),
        trait_name: Some("fmt::Display".into()),
        methods: vec![MethodDef {
            signature: "fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result".into(),
            body: match_code,
            doc: None,
            attributes: vec![],
        }],
    };
    gen_impl_block(&impl_input)
}

// ---------------------------------------------------------------------------
// Main impl block — groups, transitions, guards via impl_block + match_arm
// ---------------------------------------------------------------------------

fn build_main_impl(decl: &StateMachineDecl) -> String {
    let mut methods: Vec<MethodDef> = Vec::new();

    // Group methods
    for group in &decl.groups {
        let variants: Vec<String> = group.states.iter().map(|s| format!("Self::{s}")).collect();
        methods.push(MethodDef {
            signature: format!("pub fn {}(&self) -> bool", group.method),
            body: format!(
                "matches!(self,\n    {}\n)",
                variants.join(" | ")
            ),
            doc: group.doc.clone(),
            attributes: vec![],
        });
    }

    // try_transition method
    {
        let mut arms: Vec<MatchArmDef> = Vec::new();
        for t in &decl.transitions {
            let mut comment_parts: Vec<String> = Vec::new();
            if let Some(ms) = t.debounce_ms {
                comment_parts.push(format!("debounce: {ms}ms"));
            }
            if let Some(ref trigger) = t.trigger {
                comment_parts.push(format!("\u{2014} {trigger}"));
            }
            let doc = if comment_parts.is_empty() {
                None
            } else {
                Some(comment_parts.join(" "))
            };
            arms.push(MatchArmDef {
                pattern: format!("(Self::{}, Self::{})", t.from, t.to),
                body: "Ok(())".into(),
                doc,
            });
        }

        let match_code = gen_match_expr(&MatchExprInput {
            subject: "(from, to)".into(),
            arms,
            fallback: Some(format!("Err({}TransitionError {{ from, to }})", decl.enum_name)),
            indent: 0,
        });
        let body = format!(
            "if from == to {{ return Ok(()); }} // no-op\n{}",
            match_code
        );

        methods.push(MethodDef {
            signature: format!(
                "pub fn try_transition(from: Self, to: Self) -> Result<(), {}TransitionError>",
                decl.enum_name
            ),
            body,
            doc: Some("Validate a state transition against the Lisp-declared whitelist.\nReturns Ok(()) if the transition is legal, Err with details if not.".into()),
            attributes: vec![],
        });
    }

    // debounce_ms method
    {
        let debounced: Vec<&TransitionDecl> = decl.transitions.iter()
            .filter(|t| t.debounce_ms.is_some())
            .collect();

        if !debounced.is_empty() {
            let arms: Vec<MatchArmDef> = debounced.iter().map(|t| MatchArmDef {
                pattern: format!("(Self::{}, Self::{})", t.from, t.to),
                body: format!("Some({})", t.debounce_ms.unwrap()),
                doc: None,
            }).collect();

            let match_code = gen_match_expr(&MatchExprInput {
                subject: "(from, to)".into(),
                arms,
                fallback: Some("None".into()),
                indent: 0,
            });

            methods.push(MethodDef {
                signature: "pub fn debounce_ms(from: Self, to: Self) -> Option<u32>".into(),
                body: match_code,
                doc: Some("Returns the debounce duration in ms for a transition, or None if no debounce.".into()),
                attributes: vec![],
            });
        }
    }

    // Guard methods
    for guard in &decl.guards {
        let doc = format!("Guard: {} \u{2014} {}", guard.action, guard.error_msg);
        if let Some(ref req) = guard.requires {
            methods.push(MethodDef {
                signature: format!("pub fn ensure_{}(&self) -> Result<(), &'static str>", guard.action),
                body: format!(
                    "if *self == Self::{req} {{ Ok(()) }} else {{ Err(\"{}\") }}",
                    guard.error_msg
                ),
                doc: Some(doc.clone()),
                attributes: vec![],
            });
        }
        if let Some(ref req_not) = guard.requires_not {
            methods.push(MethodDef {
                signature: format!("pub fn ensure_{}(&self) -> Result<(), &'static str>", guard.action),
                body: format!(
                    "if *self != Self::{req_not} {{ Ok(()) }} else {{ Err(\"{}\") }}",
                    guard.error_msg
                ),
                doc: Some(doc.clone()),
                attributes: vec![],
            });
        }
    }

    // valid_transitions method
    {
        let arms: Vec<MatchArmDef> = decl.states.iter().map(|state| {
            let targets: Vec<String> = decl.transitions.iter()
                .filter(|t| t.from == state.name)
                .map(|t| format!("Self::{}", t.to))
                .collect();
            MatchArmDef {
                pattern: format!("Self::{}", state.name),
                body: if targets.is_empty() {
                    "&[]".into()
                } else {
                    format!("&[{}]", targets.join(", "))
                },
                doc: None,
            }
        }).collect();

        let match_code = gen_match_expr(&MatchExprInput {
            subject: "self".into(),
            arms,
            fallback: None,
            indent: 0,
        });

        methods.push(MethodDef {
            signature: "pub fn valid_transitions(&self) -> &'static [Self]".into(),
            body: match_code,
            doc: Some("Returns all states reachable from the current state.".into()),
            attributes: vec![],
        });
    }

    gen_impl_block(&ImplBlockInput {
        type_name: decl.enum_name.clone(),
        trait_name: None,
        methods,
    })
}

// ---------------------------------------------------------------------------
// Transition error — via struct_def + impl_block atoms
// ---------------------------------------------------------------------------

fn build_transition_error(decl: &StateMachineDecl) -> String {
    let err_name = format!("{}TransitionError", decl.enum_name);
    let mut out = String::new();

    // Struct via struct_def atom
    let struct_code = gen_struct_def(&StructDefInput {
        name: err_name.clone(),
        fields: vec![
            FieldDef {
                name: "from".into(),
                rust_type: decl.enum_name.clone(),
                visibility: Visibility::Pub,
                doc: None,
                serde_rename: None,
                serde_default: false,
                serde_skip_serializing_if: None,
                serde_default_fn: None,
                extra_field_attrs: vec![],
            },
            FieldDef {
                name: "to".into(),
                rust_type: decl.enum_name.clone(),
                visibility: Visibility::Pub,
                doc: None,
                serde_rename: None,
                serde_default: false,
                serde_skip_serializing_if: None,
                serde_default_fn: None,
                extra_field_attrs: vec![],
            },
        ],
        derives: DeriveSet {
            debug: true,
            clone: false,
            serialize: false,
            deserialize: false,
            partial_eq: false,
            custom: vec![],
        },
        doc: None,
        serde_rename_all: None,
        extra_struct_attrs: vec![],
        default_impl: false,
    });
    out.push_str(&struct_code);
    out.push('\n');

    // Display impl via impl_block atom
    let display_impl = gen_impl_block(&ImplBlockInput {
        type_name: err_name.clone(),
        trait_name: Some("fmt::Display".into()),
        methods: vec![MethodDef {
            signature: "fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result".into(),
            body: "write!(f, \"illegal state transition: {{}} -> {{}}\", self.from, self.to)".into(),
            doc: None,
            attributes: vec![],
        }],
    });
    out.push_str(&display_impl);
    out.push('\n');

    // std::error::Error impl (empty — marker trait)
    let error_impl = gen_impl_block(&ImplBlockInput {
        type_name: err_name.clone(),
        trait_name: Some("std::error::Error".into()),
        methods: vec![],
    });
    out.push_str(&error_impl);

    out
}

// ---------------------------------------------------------------------------
// Trait (Generation Gap) — via trait_contract atom
// ---------------------------------------------------------------------------

fn build_trait(tr: &TraitDecl) -> String {
    let input = TraitContractInput {
        name: tr.name.clone(),
        doc: Some("Implement in custom.rs".into()),
        methods: tr.methods.iter().map(|m| {
            TraitMethodDef {
                name: m.name.clone(),
                params: m.params.clone(),
                return_type: m.returns.clone(),
                is_async: false,
                doc: m.doc.clone(),
                has_default: false,
                has_self: true,
            }
        }).collect(),
        is_async_trait: false,
    };
    gen_trait_contract(&input)
}

// ---------------------------------------------------------------------------
// Utility
// ---------------------------------------------------------------------------

fn w(out: &mut String, indent: usize, line: &str) {
    for _ in 0..indent { out.push_str("    "); }
    out.push_str(line);
    out.push('\n');
}

