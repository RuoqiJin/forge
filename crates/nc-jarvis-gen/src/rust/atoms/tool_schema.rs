#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn simple_tool_schema() {
        let input = ToolSchemaInput {
            name: "mission_kb_remember".into(),
            description: "Record knowledge entry".into(),
            params: vec![
                ToolParam {
                    name: "category".into(),
                    json_type: JsonType::String,
                    required: true,
                    description: None,
                    enum_values: vec!["preference".into(), "memory".into()],
                    default: None,
                },
                ToolParam {
                    name: "key".into(),
                    json_type: JsonType::String,
                    required: true,
                    description: Some("Unique identifier".into()),
                    enum_values: vec![],
                    default: None,
                },
                ToolParam {
                    name: "limit".into(),
                    json_type: JsonType::Integer,
                    required: false,
                    description: None,
                    enum_values: vec![],
                    default: Some("10".into()),
                },
            ],
        };

        let code = gen_tool_schema(&input);

        assert!(code.contains("\"mission_kb_remember\""));
        assert!(code.contains("\"Record knowledge entry\""));
        assert!(code.contains("\"required\": [\"category\", \"key\"]"));
        assert!(code.contains("\"enum\": [\"preference\", \"memory\"]"));
        assert!(code.contains("\"description\": \"Unique identifier\""));
        assert!(code.contains("\"default\": 10"));
    }

    #[test]
    fn no_required_params() {
        let input = ToolSchemaInput {
            name: "mission_health".into(),
            description: "Health check".into(),
            params: vec![],
        };

        let code = gen_tool_schema(&input);
        assert!(!code.contains("\"required\""));
        assert!(code.contains("\"properties\": {"));
    }

    #[test]
    fn boolean_default() {
        let input = ToolSchemaInput {
            name: "test".into(),
            description: "test".into(),
            params: vec![ToolParam {
                name: "verbose".into(),
                json_type: JsonType::Boolean,
                required: false,
                description: None,
                enum_values: vec![],
                default: Some("false".into()),
            }],
        };

        let code = gen_tool_schema(&input);
        assert!(code.contains("\"default\": false"));
    }

    #[test]
    fn definitions_file_format() {
        let input = ToolDefinitionsInput {
            module_name: "compute/job".into(),
            tools: vec![
                ToolSchemaInput {
                    name: "mission_job_poll".into(),
                    description: "Poll async job status".into(),
                    params: vec![
                        ToolParam {
                            name: "job_id".into(),
                            json_type: JsonType::String,
                            required: true,
                            description: Some("Job ID".into()),
                            enum_values: vec![],
                            default: None,
                        },
                        ToolParam {
                            name: "action".into(),
                            json_type: JsonType::String,
                            required: false,
                            description: Some("poll, list, or cancel".into()),
                            enum_values: vec!["poll".into(), "list".into(), "cancel".into()],
                            default: None,
                        },
                    ],
                },
            ],
        };

        let code = gen_tool_definitions_file(&input);

        // Header
        assert!(code.contains("GENERATED BY FORGE"));
        assert!(code.contains("use serde_json::json;"));
        assert!(code.contains("use crate::ToolDefinition;"));

        // Function signature
        assert!(code.contains("pub fn definitions() -> Vec<ToolDefinition>"));

        // Tool content
        assert!(code.contains("\"mission_job_poll\""));
        assert!(code.contains("\"required\": [\"job_id\"]"));
        assert!(code.contains("\"enum\": [\"poll\", \"list\", \"cancel\"]"));

        // Brace balance
        let open = code.matches('{').count();
        let close = code.matches('}').count();
        assert_eq!(open, close, "unbalanced: {open} vs {close}");
    }
}
