//! Atom: tool-schema
//!
//! Generates tool registration code from a typed tool description.
//! Produces ONLY the schema definition — no handler, no dispatch, no DI.
//!
//! ## Two output formats
//!
//! ### Format A: Single expression (for embedding in vec![...])
//! ```text
//! ToolDefinition::new(
//!     "mission_kb_remember",
//!     "Record knowledge entry",
//!     json!({ ... }),
//! )
//! ```
//!
//! ### Format B: Complete `definitions()` function (for standalone files)
//! ```text
//! use serde_json::json;
//! use crate::ToolDefinition;
//!
//! pub fn definitions() -> Vec<ToolDefinition> {
//!     vec![ ... ]
//! }
//! ```

use super::w;

// JsonType is now a quark — re-export for backward compatibility
pub use crate::quarks::type_map::JsonType;

/// A single parameter in a tool's input schema.
#[derive(Debug, Clone)]
pub struct ToolParam {
    pub name: String,
    pub json_type: JsonType,
    pub required: bool,
    pub description: Option<String>,
    pub enum_values: Vec<String>,
    pub default: Option<String>,
}

/// Input for a single tool schema.
pub struct ToolSchemaInput {
    pub name: String,
    pub description: String,
    pub params: Vec<ToolParam>,
}

/// Input for generating a complete `definitions()` function with multiple tools.
pub struct ToolDefinitionsInput {
    pub module_name: String,
    pub tools: Vec<ToolSchemaInput>,
}

/// Generate a single `ToolDefinition::new(...)` expression.
pub fn gen_tool_schema(input: &ToolSchemaInput) -> String {
    let mut out = String::with_capacity(1024);

    w(&mut out, 0, "ToolDefinition::new(");
    w(&mut out, 1, &format!("\"{}\",", input.name));

    let desc = input.description.replace('"', "\\\"");
    w(&mut out, 1, &format!("\"{desc}\","));

    w(&mut out, 1, "json!({");
    w(&mut out, 2, "\"type\": \"object\",");

    let required: Vec<&str> = input
        .params
        .iter()
        .filter(|p| p.required)
        .map(|p| p.name.as_str())
        .collect();
    if !required.is_empty() {
        let req_json: Vec<String> = required.iter().map(|r| format!("\"{}\"", r)).collect();
        w(
            &mut out,
            2,
            &format!("\"required\": [{}],", req_json.join(", ")),
        );
    }

    w(&mut out, 2, "\"properties\": {");
    for (i, param) in input.params.iter().enumerate() {
        let trailing = if i < input.params.len() - 1 { "," } else { "" };
        let prop_json = gen_property_schema(param);
        w(
            &mut out,
            3,
            &format!("\"{}\": {{{}}}{}", param.name, prop_json, trailing),
        );
    }
    w(&mut out, 2, "}");

    w(&mut out, 1, "}),");
    w(&mut out, 0, ")");

    out
}

/// Generate a complete `pub fn definitions() -> Vec<ToolDefinition>` file.
///
/// This is the format used by MissionD's mcp crate — each tool domain has
/// a file with a `definitions()` function returning a vec of ToolDefinition.
pub fn gen_tool_definitions_file(input: &ToolDefinitionsInput) -> String {
    let mut out = String::with_capacity(4096);

    w(&mut out, 0, "// \u{1f916} GENERATED BY FORGE - DO NOT EDIT");
    w(
        &mut out,
        0,
        &format!(
            "// Source: .missiond/intent-tools.lisp (module {})",
            input.module_name
        ),
    );
    w(&mut out, 0, "");
    w(&mut out, 0, "use serde_json::json;");
    w(&mut out, 0, "use crate::ToolDefinition;");
    w(&mut out, 0, "");
    w(
        &mut out,
        0,
        "pub fn definitions() -> Vec<ToolDefinition> {",
    );
    w(&mut out, 1, "vec![");

    for tool in &input.tools {
        // Comment separator for readability
        w(&mut out, 2, &format!("// ===== {} =====", tool.name));

        w(&mut out, 2, "ToolDefinition::new(");

        w(&mut out, 3, &format!("\"{}\",", tool.name));

        let desc = tool.description.replace('"', "\\\"");
        w(&mut out, 3, &format!("\"{desc}\","));

        w(&mut out, 3, "json!({");
        w(&mut out, 4, "\"type\": \"object\",");

        let required: Vec<&str> = tool
            .params
            .iter()
            .filter(|p| p.required)
            .map(|p| p.name.as_str())
            .collect();
        if !required.is_empty() {
            let req_json: Vec<String> = required.iter().map(|r| format!("\"{}\"", r)).collect();
            w(
                &mut out,
                4,
                &format!("\"required\": [{}],", req_json.join(", ")),
            );
        }

        w(&mut out, 4, "\"properties\": {");
        for (i, param) in tool.params.iter().enumerate() {
            let trailing = if i < tool.params.len() - 1 { "," } else { "" };
            let prop_json = gen_property_schema(param);
            w(
                &mut out,
                5,
                &format!("\"{}\": {{{}}}{}", param.name, prop_json, trailing),
            );
        }
        w(&mut out, 4, "}");

        w(&mut out, 3, "}),");
        w(&mut out, 2, "),");
        w(&mut out, 0, "");
    }

    w(&mut out, 1, "]");
    w(&mut out, 0, "}");

    out
}

/// Generate a single property's JSON Schema fragment (inside braces).
fn gen_property_schema(param: &ToolParam) -> String {
    let mut parts = Vec::new();

    parts.push(format!("\"type\": \"{}\"", param.json_type.as_json_str()));

    if let Some(ref desc) = param.description {
        let desc = desc.replace('"', "\\\"");
        parts.push(format!("\"description\": \"{desc}\""));
    }

    if !param.enum_values.is_empty() {
        let vals: Vec<String> = param.enum_values.iter().map(|v| format!("\"{}\"", v)).collect();
        parts.push(format!("\"enum\": [{}]", vals.join(", ")));
    }

    if let Some(ref default) = param.default {
        if default.parse::<f64>().is_ok() || default == "true" || default == "false" {
            parts.push(format!("\"default\": {default}"));
        } else {
            parts.push(format!("\"default\": \"{default}\""));
        }
    }

    parts.join(", ")
}

